# Builds scripts/ref/svc_ref.c from a systemd checkout: the exit status
# table and enum, exit_status_from_string, is_clean_exit,
# exit_status_set_test (src/shared/exit-status.[ch]), safe_atou8/safe_atoi
# with mangle_base (src/basic/parse-util.c), signal_from_string and its
# table (src/basic/signal-util.c) and service_shall_restart
# (src/core/service.c) are copied verbatim; only the types they use are
# shimmed (a 256-bit bitmap, a Service with the fields read).
# Usage: python3 scripts/ref/svc_ref_build.py /path/to/systemd > scripts/ref/svc_ref.c
import re, sys
S = sys.argv[1]
def rd(p): return open(S + '/' + p).read()
def fn(src, head):
    i = src.index(head)
    j = src.index('\n}\n', i)
    return src[i:j + 3]
eh = rd('src/shared/exit-status.h'); ec = rd('src/shared/exit-status.c')
pu = rd('src/basic/parse-util.c'); su = rd('src/basic/signal-util.c'); sv = rd('src/core/service.c')
enum = eh[eh.index('enum {'):eh.index('};', eh.index('enum {')) + 2]
cls = eh[eh.index('typedef enum ExitStatusClass'):eh.index('} ExitStatusClass;') + 18]
table = ec[ec.index('const ExitStatusMapping exit_status_mappings[256]'):ec.index('};', ec.index('const ExitStatusMapping exit_status_mappings[256]')) + 2]
sigtab = su[su.index('static const char *const static_signal_table[]'):su.index('};', su.index('static const char *const static_signal_table[]')) + 2]
out = ['/* Generated by scripts/ref/svc_ref_build.py from a systemd checkout; do not edit. */\n' + open(__file__.replace('svc_ref_build.py', 'svc_ref_shim.h')).read()]
out += [enum, cls, table, sigtab]
out.append('static int static_signal_from_string(const char *s) { for (size_t i = 0; i < ELEMENTSOF(static_signal_table); i++) if (streq_ptr(s, static_signal_table[i])) return (int) i; return -EINVAL; }')
out.append(fn(pu, 'static const char *mangle_base('))
out.append(fn(pu, 'int safe_atou_full('))
out.append(fn(pu, 'int safe_atou8_full('))
out.append('static inline int safe_atou8(const char *s, uint8_t *ret) { return safe_atou8_full(s, 0, ret); }')
out.append(fn(pu, 'int safe_atoi('))
out.append(fn(su, 'int signal_from_string('))
out.append(fn(ec, 'int exit_status_from_string('))
out.append(fn(ec, 'const char* exit_status_to_string('))
out.append(fn(ec, 'const char* exit_status_class('))
out.append(fn(ec, 'bool is_clean_exit('))
out.append(fn(ec, 'bool exit_status_set_test('))
out.append('''typedef enum { SERVICE_SIMPLE, SERVICE_EXEC, SERVICE_FORKING, SERVICE_ONESHOT, SERVICE_DBUS, SERVICE_NOTIFY, SERVICE_NOTIFY_RELOAD, SERVICE_IDLE } ServiceType;
typedef enum { SERVICE_RESTART_NO, SERVICE_RESTART_ON_SUCCESS, SERVICE_RESTART_ON_FAILURE, SERVICE_RESTART_ON_ABNORMAL, SERVICE_RESTART_ON_WATCHDOG, SERVICE_RESTART_ON_ABORT, SERVICE_RESTART_ALWAYS } ServiceRestart;
typedef enum { SERVICE_SUCCESS, SERVICE_FAILURE_RESOURCES, SERVICE_FAILURE_PROTOCOL, SERVICE_FAILURE_TIMEOUT, SERVICE_FAILURE_EXIT_CODE, SERVICE_FAILURE_SIGNAL, SERVICE_FAILURE_CORE_DUMP, SERVICE_FAILURE_WATCHDOG, SERVICE_FAILURE_START_LIMIT_HIT, SERVICE_FAILURE_OOM_KILL, SERVICE_SKIP_CONDITION } ServiceResult;
typedef struct { struct { int code, status; } main_exec_status; ExitStatusSet restart_prevent_status, restart_force_status; ServiceType type; ServiceResult result; ServiceRestart restart; bool forbid_restart; } Service;''')
out.append(re.sub(r'^static ', '', fn(sv, 'static bool service_shall_restart(')))
out.append(open(__file__.replace('svc_ref_build.py', 'svc_ref_main.c')).read())
print('\n\n'.join(out))
