# Word lists and reference vectors for lib/test/fake.rce.
#
# Needs Faker 40.43.0 (pip install faker==40.43.0) under CPython 3.13.
#   python3 scripts/gen/fake_gen.py lib/test/fake.rce tests/test
# rewrites the block between "# ---- generated word lists" and "# ---- end
# of generated word lists" in lib/test/fake.rce from Faker's en_US person
# and address providers and its `la` lorem provider, and writes
# tests/test/fake_checks_2.rce: version 4 UUID texts from CPython's uuid
# module (uuid.UUID(bytes=..., version=4)) and ISO dates and RFC 3339
# timestamps from CPython's datetime, over seeded random inputs and the
# ends of the supported range.
import datetime, os, random, sys, uuid
import faker
from faker.providers.person.en_US import Provider as Person
from faker.providers.address.en_US import Provider as Address
from faker.providers.lorem.la import Provider as Lorem

assert faker.VERSION == '40.43.0', faker.VERSION
MOD, OUT = sys.argv[1], sys.argv[2]
R = random.Random(20261027)

def top(d, n):
    return [k for k, _ in sorted(d.items(), key=lambda kv: (-kv[1], kv[0]))[:n]]

fem, mal = top(Person.first_names_female, 30), top(Person.first_names_male, 30)
first = [x for pair in zip(fem, mal) for x in pair]
last = top(Person.last_names, 50)
SUFFIX = ['Street', 'Avenue', 'Road', 'Lane', 'Drive', 'Court', 'Place', 'Way', 'Circle', 'Trail', 'Parkway',
          'Square', 'Loop', 'Path', 'Ridge', 'Run', 'Crossing', 'Grove', 'Terrace', 'Park']
assert all(x in Address.street_suffixes for x in SUFFIX)
prefixes = list(Address.city_prefixes)
suffixes = []
for x in Address.city_suffixes:
    if x not in suffixes:
        suffixes.append(x)
states = list(Address.states_abbr)
assert len(states) == 51
words = list(Lorem.word_list)

def rlist(name, xs, per=8):
    rows = []
    for i in range(0, len(xs), per):
        rows.append('        ' + ', '.join('"%s"' % x for x in xs[i:i + per]))
    return 'fn %s() -> List[text]\n    return [\n%s\n    ]\n' % (name, ',\n'.join(rows))

block = '\n'.join([
    '# ---- generated word lists (scripts/gen/fake_gen.py); do not edit',
    '# Faker 40.43.0 en_US person: the 30 heaviest female and male first',
    '# names, interleaved, and the 50 heaviest last names.',
    rlist('tf_first_names', first),
    '# Faker 40.43.0 en_US address: chosen street suffixes, the city prefixes,',
    '# the distinct city suffixes and the 51 state codes.',
    rlist('tf_street_suffixes', SUFFIX),
    rlist('tf_city_prefixes', prefixes),
    rlist('tf_city_suffixes', suffixes),
    rlist('tf_states', states, 13),
    '# Faker 40.43.0 la lorem word list.',
    rlist('tf_words', words, 10),
    rlist('tf_last_names', last),
    '# ---- end of generated word lists',
])
src = open(MOD).read()
a = src.index('# ---- generated word lists')
b = src.index('# ---- end of generated word lists') + len('# ---- end of generated word lists')
open(MOD, 'w').write(src[:a] + block + src[b:])

EPOCH = datetime.date(1970, 1, 1)
def iso(days):
    return (EPOCH + datetime.timedelta(days=days)).isoformat()
def stamp(secs):
    d = datetime.datetime(1970, 1, 1, tzinfo=datetime.timezone.utc) + datetime.timedelta(seconds=secs)
    return '%04d-%02d-%02dT%02d:%02d:%02dZ' % (d.year, d.month, d.day, d.hour, d.minute, d.second)

DMIN = (datetime.date(1, 1, 1) - EPOCH).days
DMAX = (datetime.date(9999, 12, 31) - EPOCH).days
assert (DMIN, DMAX) == (-719162, 2932896)
days = sorted({DMIN, DMAX, 0, -1, 1, 59, 60, 789, 10957, 11016, 11017, 24836, -36524, -141427, -146097, 2932835}
              | {R.randint(DMIN, DMAX) for _ in range(60)})
secs = sorted({0, -1, 1, 86399, 86400, -86400, -86401, 951782400, 2145916799, DMIN * 86400, DMAX * 86400 + 86399}
              | {R.randint(DMIN * 86400, DMAX * 86400 + 86399) for _ in range(40)})
uu = [bytes(16), bytes([255] * 16)] + [bytes(R.getrandbits(8) for _ in range(16)) for _ in range(40)]

with open(os.path.join(OUT, 'fake_checks_2.rce'), 'w') as f:
    f.write('# Checks for lib/test/fake.rce: version 4 UUID texts against CPython uuid,\n')
    f.write('# dates and RFC 3339 timestamps against CPython datetime.\n')
    f.write('# Generated by scripts/gen/fake_gen.py (CPython %d.%d); do not edit.\n\n' % sys.version_info[:2])
    f.write('fn fk_uu(b: List[i64]) -> text = fake_uuid_of(&b)\n\n')
    f.write('# uuid.UUID(bytes=b, version=4): %d vectors\n' % len(uu))
    for b in uu:
        f.write('check fk_uu([%s]) == "%s"\n' % (', '.join(str(x) for x in b), uuid.UUID(bytes=b, version=4)))
    f.write('\n# datetime.date(1970, 1, 1) + timedelta(days): %d vectors\n' % len(days))
    for d in days:
        f.write('check fake_date_of(%s) == "%s"\n' % (('(0 - %d)' % -d) if d < 0 else str(d), iso(d)))
    f.write('\n# datetime(1970, 1, 1, tzinfo=utc) + timedelta(seconds): %d vectors\n' % len(secs))
    for t in secs:
        f.write('check fake_datetime_of(%s) == "%s"\n' % (('(0 - %d)' % -t) if t < 0 else str(t), stamp(t)))
    f.write('\n# outside 0001-01-01..9999-12-31: ""\n')
    f.write('check fake_date_of(%d) == "" and fake_date_of(0 - %d) == ""\n' % (DMAX + 1, -(DMIN - 1)))
    f.write('check fake_datetime_of(%d) == "" and fk_uu([1, 2, 3]) == ""\n' % ((DMAX + 1) * 86400))
