# Checks for lib/os/perm.rce.
#   filemode: CPython 3.13 stat.filemode (the C _stat module) for every
#     permission value of a regular file and 64 seeded values of each
#     other file type.
#   chmod: GNU coreutils chmod (9.7 on the generating box) run on real
#     files and directories: seeded symbolic and octal modes, start modes
#     and umasks; the resulting st_mode, whether chmod warned that the
#     umask surprised it ("new permissions are", only diagnosed when the
#     mode is passed as an option such as -w), or that the mode is invalid.
#   Landlock: every LANDLOCK_ACCESS_FS_*, _NET_* and _SCOPE_* value of
#     include/uapi/linux/landlock.h at Linux v6.17 (vectors/os/landlock.h).
#   derived: the POSIX 4.5 access check, SIDs (MS-DTYP 2.4.2 text and
#     binary, well-known SIDs), the ACE-list access check, Landlock ABI
#     rights and rulesets, and the grant mapping.
# Usage: python3 scripts/gen/perm_gen.py > tests/os/perm_checks.rce
import os, random, re, stat, subprocess, sys, tempfile
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '../..')
R = random.Random(36)
def q(s):
    o = ''
    for c in s:
        o += {'"': '\\"', '\\': '\\\\'}.get(c) or c
    return '"' + o + '"'
out = []
TYPES = [stat.S_IFREG, stat.S_IFDIR, stat.S_IFLNK, stat.S_IFCHR, stat.S_IFBLK, stat.S_IFIFO, stat.S_IFSOCK, 0]
fm = 0
for p in range(4096):
    out.append('check filemode(%d) == %s' % (stat.S_IFREG | p, q(stat.filemode(stat.S_IFREG | p)))); fm += 1
for t in TYPES[1:]:
    for _ in range(64):
        p = R.randrange(4096); out.append('check filemode(%d) == %s' % (t | p, q(stat.filemode(t | p)))); fm += 1
# chmod
def expr():
    cl = []
    for _ in range(R.randint(1, 3)):
        who = ''.join(R.choice('ugoa') for _ in range(R.choice([0, 0, 1, 1, 2])))
        acts = ''
        for _ in range(R.randint(1, 2)):
            op = R.choice('+-=')
            if R.random() < .15: acts += op + R.choice('ugo')
            else: acts += op + ''.join(R.choice('rwxXst') for _ in range(R.randint(0, 3)))
        cl.append(who + acts)
    return ','.join(cl)
BAD = ['', 'u', 'z+x', 'u+q', '+x,', '8', '7777x', 'u+x,,g+w', 'ug', '0x7', '12345']
cases = []
with tempfile.TemporaryDirectory() as d:
    for i in range(1400):
        isdir = R.random() < .35
        start = R.randrange(4096) if R.random() < .7 else R.choice([0o644, 0o755, 0o2755, 0o600, 0])
        um = R.choice([0o022, 0o077, 0, 0o027, R.randrange(512)])
        e = R.choice(BAD) if i % 25 == 0 else ('%o' % R.randrange(4096) if R.random() < .1 else expr())
        if R.random() < .05: e = '0' + '%04o' % R.randrange(4096)
        f = os.path.join(d, 'x%d' % i)
        os.mkdir(f) if isdir else open(f, 'w').close()
        os.chmod(f, start)
        st0 = os.stat(f).st_mode
        if st0 & 0o7777 != start: os.chmod(f, 0o700); continue  # kernel did not set a start bit
        dash = e.startswith('-') and not e.startswith('--') and R.random() < .7  # as an option: GNU diagnoses umask surprises
        cmd = 'umask %o; chmod "$1" "$2"' if dash else 'umask %o; chmod -- "$1" "$2"'
        r = subprocess.run(['sh', '-c', cmd % um, 'sh', e, f], capture_output=True, text=True)
        m = os.stat(f).st_mode
        os.chmod(f, 0o700)
        if 'invalid mode' in r.stderr or (r.returncode != 0 and 'new permissions' not in r.stderr):
            cases.append((st0, e, um, None, False, False))
        else:
            cases.append((st0, e, um, m, dash, 'new permissions are' in r.stderr))
for st0, e, um, m, dash, w in cases:
    if m is None: out.append('check chm(%d, %s, %d) == -1' % (st0, q(e), um))
    else: out.append('check chm(%d, %s, %d) == %d and surprise(%d, %s, %d, %s) == %s' % (st0, q(e), um, m, st0, q(e), um, 'true' if dash else 'false', 'true' if w else 'false'))
# Landlock constants
h = open(os.path.join(ROOT, 'vectors/os/landlock.h')).read()
ll = 0
for name, sh in re.findall(r'#define LANDLOCK_(ACCESS_FS_\w+|ACCESS_NET_\w+|SCOPE_\w+)\s+\(1ULL << (\d+)\)', h):
    rn = 'LL_' + name.replace('ACCESS_FS_', '').replace('ACCESS_', '')
    out.append('check %s == %d' % (rn, 1 << int(sh))); ll += 1
nofficial = len(out)
D = open(os.path.join(ROOT, 'scripts/gen/perm_derived.rce')).read()
H = '''# Generated by scripts/gen/perm_gen.py; do not edit.
fn chm(m: i64, s: text, u: i64) -> i64
    let r = chmod(m, &s, u) catch Chmod(mode: -1, naive: -1)
    return r.mode
fn surprise(m: i64, s: text, u: i64, dash: bool) -> bool
    let r = chmod(m, &s, u) catch Chmod(mode: -1, naive: -1)
    return dash and r.mode & ~r.naive & 4095 != 0
'''
sys.stdout.write(H + '\n'.join(out) + '\n' + D)
print('filemode %d, chmod %d (%d invalid), landlock constants %d, derived %d' % (fm, len(cases), sum(1 for c in cases if c[3] is None), ll, D.count('\ncheck ') + D.startswith('check')), file=sys.stderr)
