def canon(attrs, data=None, kind=None):
    d = {k: v for k, v in attrs.items() if v is not None}
    if kind == 'json': d['data'] = data
    elif kind == 'text': d['data'] = data
    elif kind == 'bin': d['data_base64'] = base64.b64encode(data).decode()
    return json.dumps(d, sort_keys=True, separators=(',', ':'), ensure_ascii=False)

