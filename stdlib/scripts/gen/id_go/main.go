// Usage: cd scripts/gen/id_go && go run . (Go 1.24; go.mod pins
// go.jetify.com/typeid v1.3.0 and github.com/segmentio/ksuid v1.0.4).
// Writes tests/id/id_checks_go.rce: the TypeID and KSUID parts of
// lib/id/id.rce against the reference implementations (seed 20261027):
//   - the TypeID specification's valid.json and invalid.json
//     (vectors/id/typeid/), every case;
//   - typeid FromUUIDBytesWithPrefix on random prefixes (valid and not)
//     and UUIDs, and FromString on random and mutated text;
//   - ksuid FromParts, String, Parse (valid symbols, up to and past the
//     160-bit bound), Timestamp, Next and Prev away from the wrap, and
//     Sequence.Next.
// Derived vectors, not official ones, except the two JSON suites.
package main

import (
	"encoding/hex"
	"encoding/json"
	"fmt"
	"math/rand"
	"os"
	"path/filepath"
	"strings"
	"time"

	"github.com/segmentio/ksuid"
	"go.jetify.com/typeid"
)

const head = `# Generated by scripts/gen/id_go (go.jetify.com/typeid v1.3.0,
# github.com/segmentio/ksuid v1.0.4, Go 1.24); do not edit.

fn tg_hex(b: List[i64]) -> text
    let d = "0123456789abcdef".chars()
    var o = ""
    for x in b
        o = o + copy(d[(x >> 4) as usize]) + copy(d[(x & 15) as usize])
    return o

fn tg_fmt(p: text, u: List[i64]) -> text = typeid_format(&p, &u) catch "bad"

fn tg_parse(s: text) -> text
    let t = typeid_parse(&s) catch TypeId(prefix: "bad", uuid: [])
    if t.uuid.len() == 0
        return "bad"
    return t.prefix + " " + (uuid_format(&t.uuid) catch "bad")

fn tk_new(sec: i64, r: List[i64]) -> text
    let k = ksuid_new(sec, &r) catch [1]
    return ksuid_encode(&k) catch "bad"

fn tk_parse(s: text) -> text
    let k = ksuid_parse(&s) catch [1]
    if k.len() != 20
        return "bad"
    let t = ksuid_unix_s(&k) catch -1
    return tg_hex(k) + " " + t.tostr()

fn tk_np(s: text) -> text
    let k = ksuid_parse(&s) catch [1]
    let n = ksuid_next(&k) catch [1]
    let p = ksuid_prev(&k) catch [1]
    return (ksuid_encode(&n) catch "bad") + " " + (ksuid_encode(&p) catch "bad")

fn tk_seq(s: text, n: i64) -> List[text]
    let k = ksuid_parse(&s) catch [1]
    var o: List[text] = []
    for i in 0..n
        let x = ksuid_with_seq(&k, i) catch [1]
        o.push(ksuid_encode(&x) catch "bad")
    return o
`

func lit(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, c := range s {
		switch {
		case c == '"':
			b.WriteString(`\"`)
		case c == '\\':
			b.WriteString(`\\`)
		case c == '\n':
			b.WriteString(`\n`)
		case c == '\t':
			b.WriteString(`\t`)
		case c == '\r':
			b.WriteString(`\r`)
		case c < 32 || (c >= 0x7f && c <= 0x9f):
			fmt.Fprintf(&b, `\u{%x}`, c)
		default:
			b.WriteRune(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func blist(b []byte) string {
	p := make([]string, len(b))
	for i, x := range b {
		p[i] = fmt.Sprint(x)
	}
	return "[" + strings.Join(p, ", ") + "]"
}

func ustr(b []byte) string {
	h := hex.EncodeToString(b)
	return h[0:8] + "-" + h[8:12] + "-" + h[12:16] + "-" + h[16:20] + "-" + h[20:]
}

type valid struct {
	Name, Typeid, Prefix, Uuid string
}

func main() {
	root := filepath.Join("..", "..", "..")
	r := rand.New(rand.NewSource(20261027))
	var out []string
	add := func(f string, a ...any) { out = append(out, fmt.Sprintf(f, a...)) }

	// ---- the TypeID specification's suites ----
	var vs []valid
	var is []valid
	for _, x := range []struct {
		f string
		v *[]valid
	}{{"valid.json", &vs}, {"invalid.json", &is}} {
		data, err := os.ReadFile(filepath.Join(root, "vectors", "id", "typeid", x.f))
		if err != nil {
			panic(err)
		}
		if err := json.Unmarshal(data, x.v); err != nil {
			panic(err)
		}
	}
	add("# TypeID specification 0.3.0: valid.json")
	for _, v := range vs {
		u, _ := hex.DecodeString(strings.ReplaceAll(v.Uuid, "-", ""))
		got, err := typeid.FromString(v.Typeid)
		if err != nil || got.Prefix() != v.Prefix || got.UUID() != v.Uuid {
			panic("typeid-go disagrees with valid.json: " + v.Name)
		}
		add("check tg_parse(%s) == %s", lit(v.Typeid), lit(v.Prefix+" "+v.Uuid))
		add("check tg_fmt(%s, %s) == %s", lit(v.Prefix), blist(u), lit(v.Typeid))
	}
	add("# TypeID specification 0.3.0: invalid.json")
	for _, v := range is {
		if _, err := typeid.FromString(v.Typeid); err == nil {
			panic("typeid-go accepts invalid.json: " + v.Name)
		}
		add("check tg_parse(%s) == \"bad\"", lit(v.Typeid))
	}

	// ---- typeid-go on random input ----
	add("# typeid v1.3.0: FromUUIDBytesWithPrefix and FromString")
	letters := "abcdefghijklmnopqrstuvwxyz"
	other := "_ABZ09-.é "
	randPrefix := func() string {
		n := r.Intn(8)
		switch r.Intn(10) {
		case 0:
			n = 63
		case 1:
			n = 64
		case 2:
			n = 0
		}
		var b strings.Builder
		for i := 0; i < n; i++ {
			if r.Intn(9) == 0 {
				c := []rune(other)
				b.WriteRune(c[r.Intn(len(c))])
			} else if r.Intn(6) == 0 {
				b.WriteByte('_')
			} else {
				b.WriteByte(letters[r.Intn(26)])
			}
		}
		return b.String()
	}
	for i := 0; i < 200; i++ {
		p := randPrefix()
		u := make([]byte, 16)
		r.Read(u)
		want := "bad"
		if id, err := typeid.FromUUIDBytesWithPrefix(p, u); err == nil {
			want = id.String()
		}
		add("check tg_fmt(%s, %s) == %s", lit(p), blist(u), lit(want))
	}
	b32 := "0123456789abcdefghjkmnpqrstvwxyz"
	mut := "_-ABilouIL8 é"
	for i := 0; i < 200; i++ {
		p := randPrefix()
		var b strings.Builder
		for k := 0; k < 26; k++ {
			if k == 0 {
				b.WriteByte(b32[r.Intn(8)])
			} else {
				b.WriteByte(b32[r.Intn(32)])
			}
		}
		s := b.String()
		if p != "" || r.Intn(3) == 0 {
			s = p + "_" + s
		}
		if i%2 == 1 {
			rs := []rune(s)
			k := r.Intn(len(rs) + 1)
			m := []rune(mut)
			switch r.Intn(3) {
			case 0:
				if k < len(rs) {
					rs = append(rs[:k], rs[k+1:]...)
				}
			case 1:
				rs = append(rs[:k], append([]rune{m[r.Intn(len(m))]}, rs[k:]...)...)
			default:
				if k < len(rs) {
					rs[k] = m[r.Intn(len(m))]
				}
			}
			s = string(rs)
		}
		want := "bad"
		if id, err := typeid.FromString(s); err == nil {
			want = id.Prefix() + " " + id.UUID()
		}
		add("check tg_parse(%s) == %s", lit(s), lit(want))
	}

	// ---- ksuid ----
	add("# ksuid v1.0.4: FromParts, String, Parse, Timestamp, Next, Prev, Sequence")
	for i := 0; i < 120; i++ {
		sec := int64(1400000000) + r.Int63n(1<<32)
		if i == 0 {
			sec = 1400000000
		}
		if i == 1 {
			sec = 1400000000 + (1 << 32) - 1
		}
		pl := make([]byte, 16+r.Intn(3))
		r.Read(pl)
		k, err := ksuid.FromParts(time.Unix(sec, 0), pl[:16])
		if err != nil {
			panic(err)
		}
		add("check tk_new(%d, %s) == %s", sec, blist(pl), lit(k.String()))
	}
	const sym = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"
	for i := 0; i < 160; i++ {
		var b strings.Builder
		for k := 0; k < 27; k++ {
			if k == 0 {
				b.WriteByte(sym[r.Intn(38)]) // 0..9A..Z and a, b: around the 160-bit bound
			} else {
				b.WriteByte(sym[r.Intn(62)])
			}
		}
		s := b.String()
		want := "bad"
		if k, err := ksuid.Parse(s); err == nil {
			want = hex.EncodeToString(k.Bytes()) + " " + fmt.Sprint(k.Time().Unix())
			if int64(k.Timestamp())+1400000000 != k.Time().Unix() {
				panic("timestamp")
			}
		}
		add("check tk_parse(%s) == %s", lit(s), lit(want))
	}
	for i := 0; i < 80; i++ {
		b := make([]byte, 20)
		r.Read(b)
		switch i % 4 {
		case 1:
			for j := 4 + r.Intn(16); j < 20; j++ {
				b[j] = 255
			}
		case 2:
			for j := 4 + r.Intn(16); j < 20; j++ {
				b[j] = 0
			}
		}
		k, _ := ksuid.FromBytes(b)
		if k == ksuid.Nil || k == ksuid.Max {
			continue
		}
		add("check tk_np(%s) == %s", lit(k.String()), lit(k.Next().String()+" "+k.Prev().String()))
	}
	for i := 0; i < 20; i++ {
		b := make([]byte, 20)
		r.Read(b)
		seed, _ := ksuid.FromBytes(b)
		seq := ksuid.Sequence{Seed: seed}
		n := 1 + r.Intn(6)
		var want []string
		for j := 0; j < n; j++ {
			k, err := seq.Next()
			if err != nil {
				panic(err)
			}
			want = append(want, lit(k.String()))
		}
		add("check tk_seq(%s, %d) == [%s]", lit(seed.String()), n, strings.Join(want, ", "))
	}

	f := filepath.Join(root, "tests", "id", "id_checks_go.rce")
	body := head + "\n" + strings.Join(out, "\n") + "\n"
	if err := os.WriteFile(f, []byte(body), 0o644); err != nil {
		panic(err)
	}
	n := 0
	for _, l := range out {
		if strings.HasPrefix(l, "check") {
			n++
		}
	}
	fmt.Println("go checks:", n)
}
