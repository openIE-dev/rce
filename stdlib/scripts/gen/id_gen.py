# Usage: python3 scripts/gen/id_gen.py (from stdlib/, CPython 3.13).
# Writes tests/id/id_checks_cpython_1.rce .. _3.rce: lib/id/id.rce against
# the CPython 3.13 uuid module (seed 20261027). Derived vectors, not
# official ones:
#  - uuid_parse on canonical, 32-digit, braced and urn:uuid: forms and
#    their mutations: accepted exactly when the grammar below matches, and
#    then with the value CPython's uuid.UUID(hex) gives;
#  - uuid_parse_lax on fuzzed ASCII text: accepted exactly when
#    uuid.UUID(hex) accepts it, with the same value;
#  - format, hex, URN, fields, variant, version, time, clock_seq and node
#    of random UUIDs against str(), .hex, .urn and the properties;
#  - uuid_with_version and uuid_v4 against UUID(bytes=..., version=...);
#  - uuid_v1 against uuid.uuid1(node, clock_seq) with time.time_ns fixed;
#  - uuid_name_input and uuid_from_hash against uuid.uuid3 and uuid.uuid5
#    (the MD5 and SHA-1 digests come from hashlib, as uuid computes them).
import os, random, re, sys, uuid, hashlib, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from rcelit import lit

assert sys.version_info[:2] == (3, 13), 'CPython 3.13 is the reference'
r = random.Random(20261027)
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'tests', 'id')

HEAD = '''# Generated by scripts/gen/id_gen.py (CPython 3.13 uuid); do not edit.

fn tc_fmt(b: List[i64]) -> text = uuid_format(&b) catch "bad"

fn tc_parse(s: text) -> text
    let b = uuid_parse(&s) catch [1]
    return tc_fmt(b)

fn tc_lax(s: text) -> text
    let b = uuid_parse_lax(&s) catch [1]
    return tc_fmt(b)

fn tc_info(b: List[i64]) -> text
    let f = uuid_fields(&b) catch UuidFields(time_low: -1, time_mid: -1, time_hi_version: -1, clock_seq_hi_variant: -1, clock_seq_low: -1, node_id: -1)
    let xs: List[i64] = [f.time_low, f.time_mid, f.time_hi_version, f.clock_seq_hi_variant, f.clock_seq_low, f.node_id, uuid_variant(&b) catch -9, uuid_version(&b) catch -9, uuid_ticks_of(&b) catch -9, uuid_clock_seq(&b) catch -9, uuid_node(&b) catch -9]
    var o = (uuid_format(&b) catch "bad") + " " + (uuid_hex(&b) catch "bad") + " " + (uuid_urn(&b) catch "bad")
    for x in xs
        o = o + " " + x.tostr()
    return o

fn tc_ver(b: List[i64], v: i64) -> text
    let u = uuid_with_version(&b, v) catch [1]
    return tc_fmt(u)

fn tc_v4(b: List[i64]) -> text
    let u = uuid_v4(&b) catch [1]
    return tc_fmt(u)

fn tc_v1(ns: i64, cs: i64, nd: i64) -> text
    let u = uuid_v1(uuid_ticks(ns), cs, nd) catch [1]
    let ms = uuid_unix_ms(&u) catch -9
    return tc_fmt(u) + " " + ms.tostr()

fn tc_named(v: i64, ns: List[i64], name: text, input: List[i64], digest: List[i64]) -> text
    let i = uuid_name_input(&ns, &name) catch [1]
    if i != input
        return "bad input"
    let u = uuid_from_hash(v, &digest) catch [1]
    return tc_fmt(u)
'''

def blist(b):
    return '[' + ', '.join(str(x) for x in b) + ']'

def rbytes(n):
    return bytes(r.getrandbits(8) for _ in range(n))

# ---------------- uuid_parse (strict grammar) ----------------
B = r'(?:[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}|[0-9a-fA-F]{32})'
GRAMMAR = re.compile(r'(?:\{' + B + r'\}|[uU][rR][nN]:[uU][uU][iI][dD]:' + B + '|' + B + r')\Z')

def rcase(s):
    return ''.join(c.upper() if r.random() < 0.5 else c.lower() for c in s)

def mutate(s):
    k = r.randrange(6)
    i = r.randrange(len(s) + 1)
    if k == 0 and len(s) > 0:
        return s[:i] + s[i + 1:]
    if k == 1:
        return s[:i] + r.choice('-{}: gxXuU0aF\t') + s[i:]
    if k == 2 and len(s) > 1:
        i = min(i, len(s) - 2)
        return s[:i] + s[i + 1] + s[i] + s[i + 2:]
    if k == 3 and len(s) > 0:
        i = min(i, len(s) - 1)
        return s[:i] + r.choice('0123456789abcdefABCDEFgG-{}: ') + s[i + 1:]
    if k == 4:
        return r.choice(['{', '}', ' ', 'urn:uuid:', 'urn:', 'uuid:']) + s
    return s + r.choice(['}', ' ', '-', '0', '\n'])

# CPython removes only a lowercase urn:uuid:; the URN scheme and NID are
# case-insensitive (RFC 8141), so the value is read with the prefix lowered.
def strict_want(s):
    if not GRAMMAR.match(s):
        return 'bad'
    if s[:9].lower() == 'urn:uuid:':
        s = 'urn:uuid:' + s[9:]
    return str(uuid.UUID(s))

def strict_cases():
    out = []
    for n in range(260):
        u = uuid.UUID(bytes=rbytes(16))
        body = str(u) if r.random() < 0.6 else u.hex
        form = r.randrange(4)
        body = [body, body.upper(), rcase(body)][r.randrange(3)]
        s = [body, '{' + body + '}', rcase('urn:uuid:') + body, 'urn:uuid:' + body][form]
        if r.random() < 0.55:
            for _ in range(r.randrange(1, 3)):
                s = mutate(s)
        want = strict_want(s)
        out.append('check tc_parse(%s) == %s' % (lit(s), lit(want)))
    for s in ['', '{}', 'urn:uuid:', '{' + '0' * 32, '0' * 32 + '}', 'URN:UUID:' + '0' * 32, '{urn:uuid:' + '0' * 32 + '}', '0' * 31 + 'g', '00000000-0000-0000-0000-00000000000', '00000000-0000-0000-0000-0000000000000']:
        want = strict_want(s)
        out.append('check tc_parse(%s) == %s' % (lit(s), lit(want)))
    return out

# ---------------- uuid_parse_lax (CPython uuid.UUID(hex)) ----------------
def cpy(s):
    try:
        return str(uuid.UUID(s))
    except ValueError:
        return 'bad'

TOK = ['urn:', 'uuid:', 'ur', 'n:', 'uu', 'id:', '{', '}', '-', '--', ' ', '\t', '\n', '\x0b', '\x0c', '\r', '\x1c', '+', '0x', '0X', '_', '__', 'g', 'x', ':', '0', 'f', 'F', 'a']

def lax_case():
    k = r.randrange(5)
    hexd = ''.join(r.choice('0123456789abcdefABCDEF') for _ in range(32))
    if k == 0:
        s = list(hexd)
        for _ in range(r.randrange(1, 5)):
            s.insert(r.randrange(len(s) + 1), r.choice(TOK))
        return ''.join(s)
    if k == 1:
        # replace a prefix with spaces, a sign, a 0x prefix or underscores
        m = r.randrange(1, 6)
        pre = ''.join(r.choice([' ', '\t', '+', '0x', '_', '0X']) for _ in range(m))
        s = pre + hexd
        s = s[:32] if r.random() < 0.7 else s
        if r.random() < 0.4:
            i = r.randrange(len(s))
            s = s[:i] + '_' + s[i + 1:]
        return s
    if k == 2:
        s = hexd[:r.randrange(20, 33)]
        s = s + ' ' * (32 - len(s)) if r.random() < 0.5 else ' ' * (32 - len(s)) + s
        return r.choice(['', '{', '{{', '}', 'urn:uuid:', 'uuid:']) + s + r.choice(['', '}', '}}', '{'])
    if k == 3:
        s = '-'.join(hexd[i:i + r.randrange(1, 9)] for i in range(0, 32, 4))
        return s
    s = ''.join(r.choice(TOK + list('0123456789abcdef') * 3) for _ in range(r.randrange(20, 45)))
    return s

def lax_cases(n):
    out = []
    for _ in range(n):
        s = lax_case()
        out.append('check tc_lax(%s) == %s' % (lit(s), lit(cpy(s))))
    return out

# ---------------- fields ----------------
VAR = {uuid.RESERVED_NCS: 0, uuid.RFC_4122: 2, uuid.RESERVED_MICROSOFT: 6, uuid.RESERVED_FUTURE: 7}

def info_cases(n):
    out = []
    specials = [bytes(16), b'\xff' * 16, uuid.NAMESPACE_DNS.bytes, uuid.NAMESPACE_URL.bytes, uuid.NAMESPACE_OID.bytes, uuid.NAMESPACE_X500.bytes]
    for i in range(n):
        if i < len(specials):
            b = specials[i]
        else:
            b = bytearray(rbytes(16))
            if r.random() < 0.5:
                b[6] = (r.randrange(16) << 4) | (b[6] & 15)
            if b[6] >> 4 == 6 and 128 <= b[8] < 192:
                b[6] = 0x40 | (b[6] & 15)
            b = bytes(b)
        u = uuid.UUID(bytes=b)
        f = u.fields
        ver = u.version if u.version is not None else -1
        xs = list(f) + [VAR[u.variant], ver, u.time, u.clock_seq, u.node]
        want = '%s %s %s %s' % (str(u), u.hex, u.urn, ' '.join(str(x) for x in xs))
        out.append('check tc_info(%s) == %s' % (blist(b), lit(want)))
    return out

def version_cases(n):
    out = []
    for _ in range(n):
        b = rbytes(16)
        v = r.randrange(1, 6)
        out.append('check tc_ver(%s, %d) == %s' % (blist(b), v, lit(str(uuid.UUID(bytes=b, version=v)))))
    for _ in range(n // 2):
        b = rbytes(r.randrange(16, 21))
        out.append('check tc_v4(%s) == %s' % (blist(b), lit(str(uuid.UUID(bytes=b[:16], version=4)))))
    return out

def v1_cases(n):
    out = []
    real = time.time_ns
    try:
        for i in range(n):
            if i % 4 == 0:
                ns = r.randrange(-2**63, 0)  # back to 1677
            else:
                ns = r.randrange(0, 2**63)
            node = r.getrandbits(48)
            cs = r.getrandbits(14)
            time.time_ns = lambda: ns
            uuid._last_timestamp = None
            u = uuid.uuid1(node, cs)
            ms = (u.time - 0x01b21dd213814000) // 10000
            out.append('check tc_v1(%d, %d, %d) == %s' % (ns, cs, node, lit('%s %d' % (u, ms))))
    finally:
        time.time_ns = real
    return out

NAMES = ['', 'www.example.com', 'http://www.python.org/', '1.3.6.1', 'c=ca', 'python.org', 'café', '中文', '\U0001f600 grin', 'a"b\\c', 'tab\there', 'x' * 70]

def named_cases(n):
    out = []
    spaces = [uuid.NAMESPACE_DNS, uuid.NAMESPACE_URL, uuid.NAMESPACE_OID, uuid.NAMESPACE_X500]
    for i in range(n):
        ns = spaces[i % 4] if i % 3 else uuid.UUID(bytes=rbytes(16))
        if i < len(NAMES):
            name = NAMES[i]
        else:
            name = ''.join(r.choice('abcdefghijklmnopqrstuvwxyz0123456789.-/:éß中\U0001f600') for _ in range(r.randrange(0, 24)))
        inp = ns.bytes + name.encode('utf-8')
        if i % 2 == 0:
            v, d, u = 3, hashlib.md5(inp).digest(), uuid.uuid3(ns, name)
        else:
            v, d, u = 5, hashlib.sha1(inp).digest(), uuid.uuid5(ns, name)
        out.append('check tc_named(%d, %s, %s, %s, %s) == %s' % (v, blist(ns.bytes), lit(name), blist(inp), blist(d), lit(str(u))))
    return out

def write(name, lines):
    with open(os.path.join(OUT, name), 'w') as f:
        f.write(HEAD + '\n' + '\n'.join(lines) + '\n')

s1 = strict_cases()
s2 = lax_cases(700)
s3 = info_cases(160) + version_cases(100) + v1_cases(100) + named_cases(120)
write('id_checks_cpython_1.rce', ['# uuid_parse: the grammar, values from uuid.UUID(hex)'] + s1)
write('id_checks_cpython_2.rce', ['# uuid_parse_lax: uuid.UUID(hex) accepts or refuses, and its value'] + s2)
write('id_checks_cpython_3.rce', ['# fields, versions 1, 3, 4 and 5'] + s3)
print('cpython checks:', len(s1), len(s2), len(s3))
