const LEX = /[\u202a-\u202e\u2066-\u2069\u061c\u200e\u200f\u200b-\u200d\u2060-\u2064\ufeff\u00ad\u034f\u180e\u115f\u1160\u17b4\u17b5\u3164\uffa0\ufff9-\ufffb\u2028\u2029\ufdd0-\ufdef\ufffe\uffff]/u;
function lit(s) {
  let o = '"';
  for (const c of s) {
    const x = c.codePointAt(0);
    if (c === '"') o += '\\"';
    else if (c === '\\') o += '\\\\';
    else if (c === '\n') o += '\\n';
    else if (c === '\t') o += '\\t';
    else if (c === '\r') o += '\\r';
    else if (x < 32 || (x >= 0x7f && x <= 0x9f) || LEX.test(c)) o += '\\u{' + x.toString(16) + '}';
    else o += c;
  }
  return o + '"';
}
