def rce_value(name, v, fmt):
    if fmt:
        return fmt(v)
    if isinstance(v, list):
        return '[' + ', '.join(ilit(x) for x in v) + ']'
    if isinstance(v, str):
        return '"' + v.replace('\\', '\\\\').replace('"', '\\"') + '"'
    if isinstance(v, dict):
        return '{' + ', '.join('%s: %s' % (ilit(k), ilit(v[k])) for k in sorted(v)) + '}'
    if name == 'rec':
        return None
    if isinstance(v, tuple):
        return '(' + ', '.join(('true' if x else 'false') if isinstance(x, bool) else ilit(x) for x in v) + ')'
    raise ValueError(v)

def find_checks(rows):
    out = []
    for name, strat, cond, g, c, fmt, cases, note in rows:
        v = find(strat, cond, settings=S)
        cfg = 'prop_cfg(1)' if cases == 100 else 'prop_cfg_cases(1, %d)' % cases
        call = 'find_val(%s, %s, %s)' % (g, c, cfg)
        if note:
            out.append('# %s: Hypothesis find gives %r. %s.' % (name, v, note))
            out.append('check fsame(%s, 1.5) and prop_float_lex(1.5) < prop_float_lex(%s)' % (call, flit(v)))
        elif name == 'rec':
            out.append('# %s: Hypothesis find gives %r' % (name, v))
            out.append('check fg_rec_is(%s, %s, %s)' % (call, rce_value('', v[0], None), ilit(v[1])))
        elif fmt is flit:
            out.append('# %s: Hypothesis find gives %r' % (name, v))
            out.append('check fsame(%s, %s)' % (call, flit(v)))
        else:
            out.append('# %s: Hypothesis find gives %r' % (name, v))
            out.append('check %s == %s' % (call, rce_value(name, v, fmt)))
    return out

