#!/usr/bin/env python3
"""Generate tests/num/stats_checks_nist_*.rce from the NIST StRD datasets.

Source: NIST Statistical Reference Datasets (https://www.itl.nist.gov/div898/strd/),
univariate summary statistics, linear least squares and ANOVA. Every
certified value is checked by its log relative error (LRE, the number of
correct significant digits, NIST's own measure) against a floor.

Each value is checked twice. NIST certifies the exact answer for the
decimal data; the module sees the data rounded to binary64, which for
NumAcc3/4, Filip and SmLs04-09 moves the exact answer itself by up to
9 digits. So (1) the result must match the exact answer for the binary
data (mpmath 1.4.1 at 400 bits) to LRE >= 12, and (2) it must match the
NIST certified value to LRE >= min(12, L - 0.5), where L is the LRE of
that binary-exact answer against the certified value (the best any
binary64 program can do on these inputs).

Run with the SciPy venv python (mpmath). Usage:
stats_nist_gen.py [NIST_DIR (default vectors/num/nist)] [--measure] [--out DIR]
"""
import os, re, sys
import mpmath as mp

mp.mp.prec = 400

UNIV = ['PiDigits', 'Lottery', 'Lew', 'Mavro', 'Michelso', 'NumAcc1', 'NumAcc2', 'NumAcc3', 'NumAcc4']
# name: (polynomial degree or 'cols', intercept)
LLS = {'Norris': (1, True), 'Pontius': (2, True), 'NoInt1': (1, False), 'NoInt2': (1, False),
       'Filip': (10, True), 'Longley': ('cols', True), 'Wampler1': (5, True), 'Wampler2': (5, True),
       'Wampler3': (5, True), 'Wampler4': (5, True), 'Wampler5': (5, True)}
ANOVA = ['SiRstv', 'SmLs01', 'SmLs02', 'SmLs03', 'SmLs04', 'SmLs05', 'SmLs06', 'SmLs07', 'SmLs08', 'SmLs09', 'AtmWtAg']

# LRE floors (digits). NIST certifies 15 significant digits; these are the
# floors this implementation is held to (see SOURCE.md for the measured LREs).
FLOOR = {}
# datasets whose fit is split over files: entries of (X^T X)^-1 per file
SPLIT = {'Filip': 2}

NUM = r'[-+]?(?:\d+\.?\d*|\.\d+)(?:[EeDd][-+]?\d+)?'

def num(s): return float(s.replace('D', 'E').replace('d', 'e'))
def f(x): return repr(float(x))

def lines(name, d):
    return open(os.path.join(d, name + '.dat'), encoding='latin-1').read().splitlines()

def data_rows(ls):
    last = max(i for i, l in enumerate(ls) if l.startswith('Data:'))
    rows = []
    for l in ls[last + 1:]:
        t = l.split()
        if not t or not all(re.fullmatch(NUM, v) for v in t): continue
        rows.append([num(v) for v in t])
    return rows

def cert_after(ls, label):
    for l in ls:
        if label in l:
            m = re.findall(NUM, l.split(label, 1)[1])
            return num(m[0])
    raise KeyError(label)

HEAD = '''# generated by scripts/gen/stats_nist_gen.py from NIST StRD (%s); checked by LRE
# (log relative error = correct significant digits) against a floor.

fn stx_lre(q: f64, c: f64) -> f64
    if q == c
        return 16.0
    let e = if c == 0.0 then st_abs(q) else st_abs(q - c) / st_abs(c)
    return 0.0 - special.cr_log(e) / 2.302585092994046
'''

def lst(xs): return '[' + ', '.join(f(x) for x in xs) + ']'

def mlre(q, c):
    q = mp.mpf(q); c = mp.mpf(c)
    if q == c: return 16.0
    return float(-mp.log10(abs(q - c) / abs(c))) if c != 0 else float(-mp.log10(abs(q)))

def emit(out, tag, items, measure):
    # items: list of (expr, cert, exact-binary value, label)
    if measure:
        out.append('const M_%s: List[f64] = %s' % (tag, '[' + ', '.join('stx_lre(%s, %s)' % (e, f(c)) for e, c, _, _ in items) + ']'))
        out.append('const X_%s: List[f64] = %s' % (tag, '[' + ', '.join('stx_lre(%s, %s)' % (e, f(float(x))) for e, _, x, _ in items) + ']'))
        return
    for e, c, x, lab in items:
        fl = min(12.0, int((mlre(x, c) - 0.5) * 10) / 10.0)
        xb = float(x)
        out.append('check stx_lre(%s, %s) >= %s  # %s, NIST certified %s' % (e, f(c), f(fl), lab, repr(c)))
        if xb != 0.0:
            out.append('check stx_lre(%s, %s) >= 12.0  # %s, exact for the binary64 data (mpmath)' % (e, f(xb), lab))

def univ(name, d, measure):
    ls = lines(name, d)
    ys = [r[0] for r in data_rows(ls)]
    mu = cert_after(ls, 'ybar:'); sd = cert_after(ls, ' s:'); r1 = cert_after(ls, 'r(1):')
    out = [HEAD % name, 'const STX_Y: List[f64] = ' + lst(ys), '']
    y = [mp.mpf(v) for v in ys]; n = len(y); m = mp.fsum(y) / n
    ss = mp.fsum((v - m) ** 2 for v in y)
    xs1 = mp.fsum((y[i] - m) * (y[i + 1] - m) for i in range(n - 1)) / ss
    it = [('mean(&STX_Y) catch 0.0', mu, m, 'NIST %s mean' % name),
          ('stdev(&STX_Y, 1) catch 0.0', sd, mp.sqrt(ss / (n - 1)), 'NIST %s sd' % name),
          ('autocorr1(&STX_Y) catch 0.0', r1, xs1, 'NIST %s r(1)' % name)]
    emit(out, name, it, measure); return [out]

def lls(name, d, measure):
    ls = lines(name, d); rows = data_rows(ls)
    deg, ic = LLS[name]
    ys = [r[0] for r in rows]
    if deg == 'cols':
        p = len(rows[0]) - 1 + 1
        a = [1.0] * len(rows)
        for j in range(1, len(rows[0])): a += [r[j] for r in rows]
        design = 'linalg.mat(%d, %d, %s) catch linalg.zeros(1, 1)' % (len(rows), p, lst(a))
        xdef = ''
    else:
        xs = [r[1] for r in rows]
        p = deg + 1 if ic else deg
        xdef = 'const STX_X: List[f64] = ' + lst(xs)
        design = 'stx_design(&STX_X, %d, %s)' % (deg, 'true' if ic else 'false')
    # certified estimates and sds
    est, sds = [], []
    for l in ls:
        m = re.match(r'\s+B(\d+)\s+(' + NUM + r')\s+(' + NUM + r')\s*$', l)
        if m: est.append(num(m.group(2))); sds.append(num(m.group(3)))
    rsd = cert_after(ls, 'Standard Deviation  ') if 'Standard Deviation  ' in '\n'.join(ls) else None
    txt = '\n'.join(ls)
    rsd = num(re.search(r'Residual\s*\n\s*Standard Deviation\s+(' + NUM + ')', txt).group(1))
    r2 = num(re.search(r'R-Squared\s+(' + NUM + ')', txt).group(1))
    reg = re.search(r'\nRegression\s+(\d+)\s+(' + NUM + r')\s+(' + NUM + r')\s+(' + NUM + '|Infinity)', txt)
    res = re.search(r'\nResidual\s+(\d+)\s+(' + NUM + r')\s+(' + NUM + ')', txt)
    out = [HEAD % name, 'const STX_Y: List[f64] = ' + lst(ys), xdef, '''
fn stx_design(x: &[f64], deg: i64, ic: bool) -> linalg.Mat
    let m = x.len()
    var a: List[f64] = []
    var p: i64 = deg
    if ic
        p = deg + 1
    for j in 0..(p as usize)
        let e = if ic then j as i64 else (j as i64) + 1
        for i in 0..m
            var v = 1.0
            for _ in 0..(e as usize)
                v = v * x[i]
            a.push(v)
    return linalg.mat(m, p as usize, a) catch linalg.zeros(1, 1)

const STX_A: linalg.Mat = %s
''' % design]
    ics = 'true' if ic else 'false'
    NOFIT = 'Ols(coef: [], se: [], resid_sd: 0.0, r2: 0.0, ss_reg: 0.0, ss_res: 0.0, df_reg: 0, df_res: 0, f: 0.0, exact: false)'
    QR = 'const STQ: OlsQr = ols_qr(&STX_A) catch OlsQr(q: linalg.zeros(1, 1), r: linalg.zeros(1, 1))'
    FULL = 'const STX: Ols = ols(&STX_A, &STX_Y, %s) catch %s' % (ics, NOFIT)
    # exact least squares for the binary64 design (built as RCE builds it)
    if deg == 'cols':
        X = [[1.0] + r[1:] for r in rows]
    else:
        X = []
        for r in rows:
            row = []
            for e in (range(deg + 1) if ic else range(1, deg + 1)):
                v = 1.0
                for _ in range(e): v = v * r[1]
                row.append(v)
            X.append(row)
    A = mp.matrix([[mp.mpf(v) for v in row] for row in X]); yv = mp.matrix([mp.mpf(v) for v in ys])
    N = A.T * A; Ni = mp.inverse(N); bx = Ni * (A.T * yv)
    rv = yv - A * bx; ssr = mp.fsum(v ** 2 for v in rv); dfr = len(ys) - A.cols
    sx = mp.sqrt(ssr / dfr)
    ym = mp.fsum(yv) / len(ys)
    sst = mp.fsum((v - ym) ** 2 for v in yv) if ic else mp.fsum(v ** 2 for v in yv)
    dfg = A.cols - 1 if ic else A.cols
    it = []
    for j, (b, s) in enumerate(zip(est, sds)):
        it.append(('STX.coef[%d]' % j, b, bx[j], 'NIST %s B%d' % (name, j)))
        if s != 0.0: it.append(('STX.se[%d]' % j, s, sx * mp.sqrt(Ni[j, j]), 'NIST %s sd(B%d)' % (name, j)))
    if rsd != 0.0: it.append(('STX.resid_sd', rsd, sx, 'NIST %s residual sd' % name))
    it.append(('STX.r2', r2, 1 - ssr / sst, 'NIST %s R^2' % name))
    it.append(('STX.ss_reg', num(reg.group(2)), sst - ssr, 'NIST %s SS regression' % name))
    if num(res.group(2)) != 0.0: it.append(('STX.ss_res', num(res.group(2)), ssr, 'NIST %s SS residual' % name))
    if reg.group(4) != 'Infinity' and num(res.group(2)) != 0.0:
        it.append(('STX.f', num(reg.group(4)), ((sst - ssr) / dfg) / (ssr / dfr), 'NIST %s F' % name))
    elif ssr == 0:
        out.append('check STX.exact  # NIST %s: exact fit, F = infinity' % name)
    out.append('check STX.df_reg == %s  # NIST %s df' % (reg.group(1), name))
    out.append('check STX.df_res == %s  # NIST %s df' % (res.group(1), name))
    k = SPLIT.get(name)
    if not k:
        out.insert(4, FULL)
        emit(out, name, it, measure); return [out]
    # comptime fuel: the coefficients and k entries of (X^T X)^-1 per file
    pre = out[:4]
    head = pre + [QR, 'const STB: List[f64] = ols_coef(&STX_A, &STQ, &STX_Y) catch []',
                  'const STE: List[f64] = []',
                  'const STX: Ols = ols_from(&STX_A, &STX_Y, %s, STB, &STE) catch %s' % (ics, NOFIT)] + out[4:]
    emit(head, name, [t for t in it if '.se[' not in t[0]], measure)
    shards = [head]
    se = [t for t in it if '.se[' in t[0]]
    for c in range(0, len(se), k):
        part = se[c:c + k]
        js = [int(re.search(r'se\[(\d+)\]', t[0]).group(1)) for t in part]
        sh = pre + [QR, 'const STB: List[f64] = ols_coef(&STX_A, &STQ, &STX_Y) catch []',
                    'const STD: List[f64] = [%s]' % ', '.join('ols_inv_diag(&STX_A, &STQ, %d)' % j for j in js),
                    'const STX: Ols = ols_from(&STX_A, &STX_Y, %s, STB, &STD) catch %s' % (ics, NOFIT)]
        emit(sh, '%s_se%d' % (name, c), [(t[0].replace('se[%d]' % j, 'se[%d]' % i), t[1], t[2], t[3]) for i, (t, j) in enumerate(zip(part, js))], measure)
        shards.append(sh)
    return shards

def anova(name, d, measure):
    ls = lines(name, d); rows = data_rows(ls); txt = '\n'.join(ls)
    k = int(max(r[0] for r in rows))
    groups = [[r[1] for r in rows if int(r[0]) == g] for g in range(1, k + 1)]
    b = re.search(r'Between\s+\w+\s+(\d+)\s+(' + NUM + r')\s+(' + NUM + r')\s+(' + NUM + ')', txt)
    w = re.search(r'Within\s+\w+\s+(\d+)\s+(' + NUM + r')\s+(' + NUM + ')', txt)
    r2 = num(re.search(r'R-Squared\s+(' + NUM + ')', txt).group(1))
    rsd = num(re.search(r'Standard Deviation\s+(' + NUM + ')', txt).group(1))
    out = [HEAD % name,
           'const STX_G: List[List[f64]] = [' + ', '.join(lst(g) for g in groups) + ']', '',
           'const STX: Anova = f_oneway(&STX_G) catch Anova(ss_between: 0.0, ss_within: 0.0, df_between: 0, df_within: 0, ms_between: 0.0, ms_within: 0.0, f: 0.0, p: 0.0, r2: 0.0, resid_sd: 0.0)', '']
    out.append('check STX.df_between == %s  # NIST %s df' % (b.group(1), name))
    out.append('check STX.df_within == %s  # NIST %s df' % (w.group(1), name))
    G = [[mp.mpf(v) for v in g] for g in groups]; al = [v for g in G for v in g]
    gm = mp.fsum(al) / len(al)
    sb = mp.fsum(len(g) * (mp.fsum(g) / len(g) - gm) ** 2 for g in G)
    sw = mp.fsum(mp.fsum((v - mp.fsum(g) / len(g)) ** 2 for v in g) for g in G)
    db = len(G) - 1; dw = len(al) - len(G)
    it = [('STX.ss_between', num(b.group(2)), sb, 'NIST %s SS between' % name),
          ('STX.ms_between', num(b.group(3)), sb / db, 'NIST %s MS between' % name),
          ('STX.f', num(b.group(4)), (sb / db) / (sw / dw), 'NIST %s F' % name),
          ('STX.ss_within', num(w.group(2)), sw, 'NIST %s SS within' % name),
          ('STX.ms_within', num(w.group(3)), sw / dw, 'NIST %s MS within' % name),
          ('STX.r2', r2, sb / (sb + sw), 'NIST %s R^2' % name),
          ('STX.resid_sd', rsd, mp.sqrt(sw / dw), 'NIST %s residual sd' % name)]
    emit(out, name, it, measure); return [out]

def main():
    d = sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith('--') else os.path.join(os.path.dirname(os.path.abspath(__file__)), '../../vectors/num/nist')
    measure = '--measure' in sys.argv
    outdir = sys.argv[sys.argv.index('--out') + 1] if '--out' in sys.argv else 'tests/num'
    jobs = [(n, univ) for n in UNIV] + [(n, lls) for n in LLS] + [(n, anova) for n in ANOVA]
    i = 0
    for n, g in jobs:
        for sh in g(n, d, measure):
            open(os.path.join(outdir, 'stats_checks_nist_%02d.rce' % i), 'w').write('\n'.join(sh) + '\n')
            i += 1

if __name__ == '__main__':
    main()
