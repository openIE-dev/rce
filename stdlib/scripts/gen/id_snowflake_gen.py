# Usage: python3 scripts/gen/id_snowflake_gen.py (from stdlib/, CPython
# 3.13 with snowflake-id 1.0.2: pip install snowflake-id==1.0.2).
# Writes tests/id/id_checks_snowflake.rce: the Snowflake part of
# lib/id/id.rce against the snowflake-id package (seed 20261027), whose
# generator reads time.time(); the generator below replaces that clock by
# recorded readings. Derived vectors, not official ones:
#  - runs of SnowflakeGenerator(instance, seq=..., epoch=..., timestamp=...)
#    against SnowGen with the same state: the same IDs, and a refusal (the
#    package returns None) exactly where the package refuses (a clock that
#    moved backwards, a used-up sequence);
#  - Snowflake(...).value against snow_make and Snowflake.parse against
#    snow_parts, on the package's 41/10/12 layout with random epochs.
import os, random, sys
import importlib.metadata as md
import snowflake
import snowflake.snowflake as sfmod

assert md.version('snowflake-id') == '1.0.2', md.version('snowflake-id')
r = random.Random(20261027)
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'tests', 'id')

HEAD = '''# Generated by scripts/gen/id_snowflake_gen.py (snowflake-id 1.0.2 under
# CPython 3.13); do not edit.

fn ts_lay(epoch: i64) -> SnowLayout = SnowLayout(epoch_ms: epoch, worker_bits: 10, seq_bits: 12)

fn ts_run(epoch: i64, worker: i64, ms0: i64, seq0: i64, ts: List[i64]) -> List[i64]
    var g = SnowGen(lay: ts_lay(epoch), worker: worker, last_ms: ms0, seq: seq0)
    var o: List[i64] = []
    for t in ts
        o.push(snow_next(&mut g, t) catch -1)
    return o

fn ts_make(epoch: i64, ms: i64, worker: i64, seq: i64) -> i64
    let l = ts_lay(epoch)
    return snow_make(&l, ms, worker, seq) catch -1

fn ts_parts(epoch: i64, sid: i64) -> List[i64]
    let l = ts_lay(epoch)
    let p = snow_parts(&l, sid) catch SnowParts(ms: -1, worker: -1, seq: -1)
    return [p.ms, p.worker, p.seq]
'''

now = [0]
sfmod.time = lambda: (now[0] + 0.5) / 1000.0

def run_case(i):
    epoch = [1288834974657, 1420070400000, 0][i % 3] if i % 4 else r.randrange(0, 1700000000000)
    t0 = epoch + r.randrange(1, 2**40)
    inst = r.randrange(1024)
    seq0 = r.choice([0, 0, 0, 4093, 4094, 4095, r.randrange(4096)])
    now[0] = t0
    g = snowflake.SnowflakeGenerator(inst, seq=seq0, epoch=epoch, timestamp=t0)
    ts, want = [], []
    t = t0
    for _ in range(r.randrange(2, 9)):
        t = max(epoch + 1, t + r.choice([0, 0, 0, 1, 1, 2, -1, -2, 7]))
        now[0] = t
        v = next(g)
        ts.append(t)
        want.append(-1 if v is None else v)
    return 'check ts_run(%d, %d, %d, %d, [%s]) == [%s]' % (epoch, inst, t0, seq0, ', '.join(map(str, ts)), ', '.join(map(str, want)))

def layout_case():
    epoch = r.randrange(0, 1700000000000)
    tsr = r.choice([0, 1, 2**41 - 2, r.randrange(2**41 - 1)])
    inst = r.randrange(1024)
    seq = r.randrange(4096)
    s = snowflake.Snowflake(timestamp=tsr, instance=inst, epoch=epoch, seq=seq)
    p = snowflake.Snowflake.parse(s.value, epoch)
    return ['check ts_make(%d, %d, %d, %d) == %d' % (epoch, epoch + tsr, inst, seq, s.value),
            'check ts_parts(%d, %d) == [%d, %d, %d]' % (epoch, s.value, p.milliseconds, p.instance, p.seq)]

lines = ['# runs of the generator'] + [run_case(i) for i in range(160)]
lines += ['# layout']
for _ in range(80):
    lines += layout_case()
with open(os.path.join(OUT, 'id_checks_snowflake.rce'), 'w') as f:
    f.write(HEAD + '\n' + '\n'.join(lines) + '\n')
print('snowflake checks:', sum(1 for x in lines if x.startswith('check')))
