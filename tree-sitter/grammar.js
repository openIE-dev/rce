// Tree-sitter port of the spec section 3 grammar (formerly rce.lark). Rule names
// and node shapes follow the former Lark tree: `?rule`s are hidden `_rule`s whose multi-child form
// is the named node; `-> alias` alternatives are named nodes.
// Layout (_NL/_INDENT/_DEDENT, spec 2.6), bracket depth and NAME (keywords
// are reserved, spec 2.4) live in src/scanner.c.
const sep1 = (r, s) => seq(r, repeat(seq(s, r)));
const list1 = (r) => seq(r, repeat(seq(',', r)), optional(','));
const chain = (sub, op) => seq(sub, repeat1(seq(op, sub)));

module.exports = grammar({
  name: 'rce',
  externals: $ => [$._NL, $._INDENT, $._DEDENT, $.NAME, '(', ')', '[', ']', '{', '}', $._skip_nl, $.INT, $.FLOAT, $.SEND, $._bad, $.comment, $._error_sentinel],
  extras: $ => [/ +/, $._skip_nl, $.comment],
  conflicts: $ => [],
  rules: {
    start: $ => seq(repeat($._NL), optional($.module_header), repeat($._item)),
    module_header: $ => seq('module', $.path, $._NL),
    _item: $ => choice($.use_decl, $.intent_decl, $.example_decl, $.check_decl, $.pub_item, $.state_decl,
      $.event_decl, $.error_decl, $.step_decl, $.impl_decl, $.extern_decl, $.node_decl, $.supervisor_decl),
    pub_item: $ => seq(optional(alias('pub', $.PUB)), choice($.const_decl, $.type_decl, $.struct_decl, $.kind_decl,
      $.trait_decl, $.fn_decl, $.actor_decl, $.protocol_decl)),

    use_decl: $ => seq('use', $.path, optional(seq('as', $.NAME)), $._NL),
    path: $ => sep1($.NAME, '.'),

    intent_decl: $ => seq('intent', $.STRING, $._NL, optional(seq($._INDENT, repeat1($._intent_line), $._DEDENT))),
    _intent_line: $ => choice($.example_decl, $.check_decl, $.doc_line),
    doc_line: $ => seq($.STRING, $._NL),
    example_decl: $ => seq('example', optional($.event_list), '->', $._outcome, $._NL),
    event_list: $ => sep1(choice($.event_ref, $.event_call), ','),
    event_ref: $ => $.NAME,
    event_call: $ => seq($.NAME, '(', optional($.args), ')'),
    _outcome: $ => choice($.outcome_value, $.outcome_refused),
    outcome_value: $ => $._expr,
    outcome_refused: $ => seq('refused', ':', $.NAME),
    check_decl: $ => seq('check', $._expr, $._NL),

    const_decl: $ => seq('const', $.NAME, optional(seq(':', $._type)), '=', $._expr, $._NL),
    type_decl: $ => seq('type', $.NAME, optional($.generics), '=', $._type, optional(seq('where', $._expr)), $._NL),
    struct_decl: $ => seq(optional(alias('linear', $.LINEAR)), 'struct', $.NAME, optional($.generics), $._NL, optional(seq($._INDENT, repeat1($.field), $._DEDENT))),
    field: $ => seq($.NAME, ':', $._type, optional(seq('=', $._expr)), $._NL),
    state_decl: $ => seq(optional(alias('replicated', $.REPLICATED)), 'state', $.NAME, $._NL, $._INDENT, repeat1($.field), $._DEDENT),
    event_decl: $ => seq(optional(alias('interrupt', $.INTERRUPT)), 'event', $.NAME, optional($.payload), optional($.priority), $._NL),
    priority: $ => seq('priority', $._expr),
    error_decl: $ => seq('error', $.NAME, optional($.payload), $._NL),
    payload: $ => seq('(', optional($.field_list), ')'),
    field_list: $ => list1($.field_item),
    field_item: $ => seq($.NAME, ':', $._type),

    kind_decl: $ => seq('kind', $.NAME, optional($.generics), $._NL, $._INDENT, repeat1($.variant), $._DEDENT),
    variant: $ => seq($.NAME, optional($.payload), $._NL),

    trait_decl: $ => seq('trait', $.NAME, optional($.generics), optional(seq(':', $.bounds)), $._NL, $._INDENT, repeat1($._trait_member), $._DEDENT),
    _trait_member: $ => choice($.assoc_type, seq($.fn_sig, $._NL)),
    assoc_type: $ => seq('type', $.NAME, optional(seq(':', $.bounds)), $._NL),
    impl_decl: $ => seq('impl', optional(seq('forall', $.generics)), $._type, optional(seq('for', $._type)), $._NL, $._INDENT, repeat1($._impl_member), $._DEDENT),
    _impl_member: $ => choice($.type_decl, $.fn_decl),

    fn_sig: $ => seq(optional(alias('comptime', $.COMPTIME)), 'fn', $.NAME, optional($.generics), '(', optional($.params), ')', optional(seq('->', $._type)), optional(seq('bound', $.INT))),
    fn_decl: $ => seq($.fn_sig, choice($.block, seq('=', $._expr, $._NL))),
    extern_decl: $ => seq('extern', $.STRING, $.fn_sig, $._NL),
    params: $ => list1($.param),
    param: $ => choice(seq(optional(alias('comptime', $.COMPTIME)), optional($.NAME), $.NAME, ':', $._type), $.self_param, $.ref_self_param, $.mut_self_param),
    self_param: $ => 'self',
    ref_self_param: $ => seq('&', 'self'),
    mut_self_param: $ => seq('&', 'mut', 'self'),

    generics: $ => seq('[', sep1($.gparam, ','), ']'),
    gparam: $ => seq(optional(alias('comptime', $.COMPTIME)), $.NAME, optional(seq(':', $.bounds))),
    bounds: $ => sep1($.type_path, '+'),

    step_decl: $ => seq('step', $.NAME, 'on', $._pattern, optional(seq('if', $._expr)), optional($.deadline), $._step_body),
    deadline: $ => seq('deadline', $._expr),
    _step_body: $ => choice($.step_arrow, $.block),
    step_arrow: $ => seq('->', $._expr, $._NL),

    actor_decl: $ => seq('actor', $.NAME, $._NL, $._INDENT, repeat1($._actor_member), $._DEDENT),
    _actor_member: $ => choice($.field, $.handler, $.fn_decl),
    handler: $ => seq('on', $._pattern, optional(seq('if', $._expr)), $._step_body),

    // ---- draft 0.6b declarations (Appendix C, book/14-draft06-concurrency.md C.11) ----
    protocol_decl: $ => seq('protocol', $.NAME, $._NL, $._INDENT, repeat1($._proto_step), $._DEDENT),
    _proto_step: $ => choice($.proto_send, $.proto_recv, $.proto_offer, $.proto_choose, $.proto_loop, $.proto_break),
    proto_send: $ => seq('send', $._type, $._NL),
    proto_recv: $ => seq('recv', $._type, $._NL),
    proto_offer: $ => seq('offer', $._NL, $._INDENT, repeat1($.proto_arm), $._DEDENT),
    proto_choose: $ => seq('choose', $._NL, $._INDENT, repeat1($.proto_arm), $._DEDENT),
    proto_arm: $ => seq($.NAME, $._NL, optional(seq($._INDENT, repeat1($._proto_step), $._DEDENT))),
    proto_loop: $ => seq('loop', $._NL, $._INDENT, repeat1($._proto_step), $._DEDENT),
    proto_break: $ => seq('break', $._NL),
    node_decl: $ => seq('node', $.NAME, '{', sep1($.NAME, ','), '}', $._NL),
    supervisor_decl: $ => seq('supervisor', $.NAME, 'strategy', $.NAME, $._NL, $._INDENT, repeat1($.sup_child), $._DEDENT),
    sup_child: $ => seq('child', $.NAME, ':', $.type_path, optional(seq('restart', $.bound)), $._NL),

    // ---- types ----
    _type: $ => $._union_type,
    _union_type: $ => choice($._opt_type, $.union_type),
    union_type: $ => seq($._opt_type, '!', $._opt_type),
    _opt_type: $ => choice($._borrow_type, $.opt_type),
    opt_type: $ => seq($._borrow_type, '?'),
    _borrow_type: $ => choice($.ref_type, $._region_type),
    ref_type: $ => seq('&', optional(alias('mut', $.MUT)), $._borrow_type),
    _region_type: $ => choice($._base_type, $.region_type),
    region_type: $ => seq($._base_type, '@', $.NAME),
    _base_type: $ => choice($.type_path, $.unit_type, $.tuple_type, seq('(', $._type, ')'), $.slice_type,
      $.array_type, $.chan_type, $.iter_type, $.session_type, $.lvar_type, $.fn_type),
    unit_type: $ => seq('(', ')'),
    tuple_type: $ => seq('(', $._type, ',', optional(list1($._type)), ')'),
    slice_type: $ => seq('[', $._type, ']'),
    array_type: $ => seq('[', $._type, ';', $._expr, ']'),
    chan_type: $ => seq('chan', $._base_type),
    iter_type: $ => seq('iter', $._base_type),
    session_type: $ => seq('session', $.type_path),
    lvar_type: $ => seq('lvar', $._base_type),
    fn_type: $ => seq('fn', '(', optional($.type_list), ')', '->', $._base_type),
    type_path: $ => seq($.path, optional(seq('[', $.type_list, ']'))),
    type_list: $ => list1($._type),

    // ---- statements ----
    block: $ => seq($._NL, $._INDENT, repeat1($._stmt), $._DEDENT),
    _stmt: $ => choice($.simple_stmt, $.let_stmt, $.var_stmt, $.if_stmt, $.while_stmt, $.loop_stmt, $.for_stmt,
      $.match_stmt, $.return_stmt, $.break_stmt, $.continue_stmt, $.emit_stmt, $.fail_stmt,
      $.spawn_stmt, $.select_stmt, $.arena_stmt, $.device_stmt, $.yield_stmt, $.comptime_stmt, $.check_decl, $.pass_stmt,
      $.par_stmt, $.budget_stmt, $.deadline_stmt,
      $.group_stmt, $.barrier_stmt, $.scope_stmt, $.atomic_stmt),
    simple_stmt: $ => seq($._expr, optional(choice(seq($.assign_op, $._expr), seq($.SEND, $._expr))), $._NL),
    assign_op: $ => choice('=', '+=', '-=', '*=', '/=', '%=', '&=', '|=', '^=', '<<=', '>>='),
    let_stmt: $ => seq('let', $._pattern, optional(seq(':', $._type)), '=', $._expr, $._NL),
    var_stmt: $ => seq('var', $.NAME, optional(seq(':', $._type)), '=', $._expr, $._NL),
    if_stmt: $ => seq('if', $._expr, $.block, repeat($.elif_clause), optional($.else_clause)),
    elif_clause: $ => seq('elif', $._expr, $.block),
    else_clause: $ => seq('else', $.block),
    while_stmt: $ => seq('while', $._expr, optional($.bound), $.block),
    loop_stmt: $ => seq('loop', optional($.bound), $.block),
    bound: $ => seq('bound', $._expr),
    for_stmt: $ => seq('for', $._pattern, 'in', $._expr, optional(alias('par', $.PAR)), $.block),
    match_stmt: $ => seq('match', $._expr, $._NL, $._INDENT, repeat1($.arm), $._DEDENT),
    arm: $ => seq($._pattern, optional(seq('if', $._expr)), $._arm_body),
    _arm_body: $ => choice(seq('->', $._inline_stmt), $.block),
    _inline_stmt: $ => choice($.simple_stmt, $.return_stmt, $.break_stmt, $.continue_stmt, $.pass_stmt, $.emit_stmt, $.fail_stmt, $.yield_stmt),
    return_stmt: $ => seq('return', optional($._expr), $._NL),
    break_stmt: $ => seq('break', $._NL),
    continue_stmt: $ => seq('continue', $._NL),
    pass_stmt: $ => seq('pass', $._NL),
    emit_stmt: $ => seq('emit', $._expr, $._NL),
    fail_stmt: $ => seq('fail', $._expr, $._NL),
    yield_stmt: $ => seq('yield', $._expr, $._NL),
    spawn_stmt: $ => seq('spawn', $._expr, optional($.priority), optional($.join_handle), $._NL),
    join_handle: $ => seq('->', $.NAME),
    select_stmt: $ => seq('select', optional(alias('nondet', $.NONDET)), $._NL, $._INDENT, repeat1($._select_arm), $._DEDENT),
    _select_arm: $ => choice($.sel_recv, $.sel_send, $.sel_after, $.sel_default),
    sel_recv: $ => seq('recv', $._pattern, 'from', $._expr, $._arm_body),
    sel_send: $ => seq('send', $._expr, 'to', $._expr, $._arm_body),
    sel_after: $ => seq('after', $._expr, $._arm_body),
    sel_default: $ => seq('default', $._arm_body),
    arena_stmt: $ => seq('with', 'arena', $.NAME, optional($.bound), $.block),
    device_stmt: $ => seq('with', 'device', $.NAME, optional($.bound), $.block),
    comptime_stmt: $ => seq('comptime', $.block),
    // draft 0.6 (Appendix C, book/14-draft06-concurrency.md C.2)
    par_stmt: $ => seq('par', $._NL, $._INDENT, repeat1($.branch), $._DEDENT),
    branch: $ => seq('branch', $.NAME, $.block),
    budget_stmt: $ => seq('with', 'budget', $._expr, $.block),
    deadline_stmt: $ => seq('with', 'deadline', $._expr, $.block, optional($.else_clause)),
    // draft 0.6b (C.11)
    group_stmt: $ => seq('with', 'group', $.NAME, 'lanes', $._expr, $.block),
    barrier_stmt: $ => seq('barrier', $._NL),
    scope_stmt: $ => seq('scope', $.block),
    atomic_stmt: $ => seq('atomic', $.block),

    // ---- expressions ----
    _expr: $ => choice($.try_expr, $.if_expr, $.lambda, $._catch_expr),
    try_expr: $ => seq('try', $._catch_expr, optional(seq('else', $._catch_expr))),
    if_expr: $ => seq('if', $._expr, 'then', $._catch_expr, 'else', $._catch_expr),
    lambda: $ => seq('fn', '(', optional($.params), ')', '=>', $._catch_expr),
    _catch_expr: $ => choice($._or_expr, $.catch_expr),
    catch_expr: $ => seq($._or_expr, 'catch', optional(seq('|', $.NAME, '|')), $._or_expr),
    _or_expr: $ => choice($._and_expr, $.or_expr),
    or_expr: $ => chain($._and_expr, 'or'),
    _and_expr: $ => choice($._not_expr, $.and_expr),
    and_expr: $ => chain($._not_expr, 'and'),
    _not_expr: $ => choice($.not_op, $._cmp_expr),
    not_op: $ => seq('not', $._not_expr),
    _cmp_expr: $ => choice($._range_expr, $.cmp_expr),
    cmp_expr: $ => seq($._range_expr, $.cmp_op, $._range_expr),
    cmp_op: $ => choice('==', '!=', '<=', '>=', '<', '>', 'in', seq('not', 'in')),
    _range_expr: $ => choice($._bor_expr, $.range_expr),
    range_expr: $ => seq($._bor_expr, $.range_op, $._bor_expr),
    range_op: $ => choice('..=', '..'),
    _bor_expr: $ => choice($._bxor_expr, $.bor_expr),
    bor_expr: $ => chain($._bxor_expr, '|'),
    _bxor_expr: $ => choice($._band_expr, $.bxor_expr),
    bxor_expr: $ => chain($._band_expr, '^'),
    _band_expr: $ => choice($._shift_expr, $.band_expr),
    band_expr: $ => chain($._shift_expr, '&'),
    _shift_expr: $ => choice($._add_expr, $.shift_expr),
    shift_expr: $ => chain($._add_expr, $.shift_op),
    shift_op: $ => choice('<<', '>>'),
    _add_expr: $ => choice($._mul_expr, $.add_expr),
    add_expr: $ => chain($._mul_expr, $.add_op),
    add_op: $ => choice('+', '-'),
    _mul_expr: $ => choice($._cast_expr, $.mul_expr),
    mul_expr: $ => chain($._cast_expr, $.mul_op),
    mul_op: $ => choice('*', '/', '%'),
    _cast_expr: $ => choice($._unary_expr, $.cast_expr),
    cast_expr: $ => seq($._unary_expr, 'as', $._base_type),
    _unary_expr: $ => choice($.neg, $.bitnot, $.borrow, $.recv, $.comptime_expr, $._postfix),
    neg: $ => seq('-', $._unary_expr),
    bitnot: $ => seq('~', $._unary_expr),
    borrow: $ => seq('&', optional(alias('mut', $.MUT)), $._unary_expr),
    recv: $ => seq($.SEND, $._unary_expr),
    comptime_expr: $ => seq('comptime', $._unary_expr),
    _postfix: $ => choice($._primary, $.call, $.index, $.slice, $.member, $.tuple_member),
    call: $ => seq($._postfix, '(', optional($.args), ')'),
    index: $ => seq($._postfix, '[', sep1($._expr, ','), ']'),
    slice: $ => seq($._postfix, '[', optional($.slice_lo), ':', optional($.slice_hi), ']'),
    slice_lo: $ => $._expr,
    slice_hi: $ => $._expr,
    member: $ => seq($._postfix, '.', $.member_name),
    tuple_member: $ => seq($._postfix, '.', $.INT),
    args: $ => list1($.arg),
    arg: $ => seq(optional(seq($.NAME, ':')), $._expr),
    _primary: $ => choice($.name, $.self_ref, $.INT, $.FLOAT, $.STRING, $.true, $.false, $.none, $.unit,
      seq('(', $._expr, ')'), $.tuple, $.list_empty, $.list, $.list_repeat, $.list_comp, $.map_empty, $.map, $.chan_new),
    name: $ => $.NAME,
    self_ref: $ => 'self',
    true: $ => 'true',
    false: $ => 'false',
    none: $ => 'none',
    unit: $ => seq('(', ')'),
    tuple: $ => seq('(', $._expr, ',', optional(list1($._expr)), ')'),
    list_empty: $ => seq('[', ']'),
    list: $ => seq('[', list1($._expr), ']'),
    list_repeat: $ => seq('[', $._expr, ';', $._expr, ']'),
    list_comp: $ => seq('[', $._expr, 'for', $._pattern, 'in', $._or_expr, optional(seq('if', $._or_expr)), ']'),
    map_empty: $ => seq('{', '}'),
    map: $ => seq('{', list1($.map_entry), '}'),
    chan_new: $ => seq('chan', '[', $._type, ']', '(', optional($._expr), ')'),
    map_entry: $ => seq($._expr, ':', $._expr),
    member_name: $ => choice($.NAME, 'actor', 'after', 'and', 'arena', 'as', 'bound', 'break', 'catch', 'chan', 'check',
      'comptime', 'const', 'continue', 'default', 'device', 'elif', 'else', 'emit', 'error', 'event', 'example', 'extern', 'fail', 'false',
      'fn', 'for', 'forall', 'from', 'if', 'impl', 'in', 'intent', 'iter', 'kind', 'let', 'linear', 'loop', 'match', 'module',
      'mut', 'none', 'not', 'on', 'or', 'pass', 'pub', 'recv', 'refused', 'return', 'select', 'self', 'send', 'spawn',
      'state', 'step', 'struct', 'then', 'to', 'trait', 'true', 'try', 'type', 'use', 'var', 'while', 'with', 'yield',
      'par', 'branch', 'nondet', 'budget', 'deadline', 'priority',
      'replicated', 'interrupt', 'session', 'lvar', 'group', 'lanes', 'barrier', 'scope', 'atomic',
      'protocol', 'offer', 'choose', 'node', 'supervisor', 'strategy', 'child', 'restart'),

    // ---- patterns ----
    _pattern: $ => $._alt_pattern,
    _alt_pattern: $ => choice($._atom_pattern, $.alt_pattern),
    alt_pattern: $ => chain($._atom_pattern, '|'),
    _atom_pattern: $ => choice($.wildcard, $.name_pat, $.ctor_pat, $._literal_pat, $.range_pat, $.tuple_pat, seq('(', $._pattern, ')')),
    wildcard: $ => '_',
    name_pat: $ => $.path,
    ctor_pat: $ => seq($.path, '(', optional($.pat_args), ')'),
    range_pat: $ => seq($._literal_pat, $.range_op, $._literal_pat),
    tuple_pat: $ => seq('(', $._pattern, ',', optional(list1($._pattern)), ')'),
    _literal_pat: $ => choice($.literal_pat, $.neg_literal_pat, $.true_pat, $.false_pat, $.none_pat),
    literal_pat: $ => choice($.INT, $.FLOAT, $.STRING),
    neg_literal_pat: $ => seq('-', $.INT),
    true_pat: $ => 'true',
    false_pat: $ => 'false',
    none_pat: $ => 'none',
    pat_args: $ => list1($.pat_arg),
    pat_arg: $ => seq(optional(seq($.NAME, ':')), $._pattern),

    // ---- lexical ----
    STRING: $ => token(/"([^"\\\n]|\\["\\nrt0]|\\u\{[0-9A-Fa-f]{1,6}\})*"/),
    // INT, FLOAT and SEND are lexed by the scanner, longest match as in Lark
  },
});
