#!/usr/bin/env python3
"""Generate the README "Status" block from the files in reports/ (no number is typed).

  tools/readme_status.py            rewrite the block between the markers in README.md
  tools/readme_status.py --check    fail if README.md differs from what the reports give
  tools/readme_status.py --print    print the block

Every figure is counted from reports/*.json (and the test tree for the file
count). Where two reports disagree on a count, the block says so and gives both.
"""
import glob, json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BEGIN, END = "<!-- status:begin (generated by tools/readme_status.py; do not edit) -->", "<!-- status:end -->"


def load(name):
    return json.load(open(ROOT / "reports" / name))


def pct(a, b):
    return f"{100.0 * a / b:.1f}%" if b else "n/a"


def block():
    res = {}
    for f in sorted(glob.glob(str(ROOT / "reports" / "results-*.json"))):
        d = json.load(open(f))
        res[d["adapter"]] = d
    # the tally is recounted from the per-test results, and checked against the stored tally
    tally = {}
    for a, d in res.items():
        t = {}
        for r in d["results"]:
            t[r["status"]] = t.get(r["status"], 0) + 1
        if t != d["tally"]:
            sys.exit(f"reports/results-{a}.json: stored tally {d['tally']} != recount {t}")
        tally[a] = t
    cov, mut, par, ts = load("coverage.json"), load("mutation.json"), load("parity.json"), load("tree-sitter.json")
    allfiles = sum(1 for _ in (ROOT / "tests").rglob("*.rce"))
    fixtures = sum(1 for p in (ROOT / "tests").rglob("*.rce") if "_FIXTURE" in p.name)
    files = allfiles - fixtures
    ref = tally["reference"]
    nref = len(res["reference"]["results"])
    L = []
    L.append(f"Generated from `reports/` by `tools/readme_status.py` (`--check` verifies it). Every figure below is counted from the report files.")
    L.append("")
    lang = cov["profiles"]["language"]
    L.append(f"- Tests: {files} test files under `tests/` ({allfiles} `.rce` files, of which {fixtures} named `_FIXTURE` are support files, not tests); the reference run has {nref} results; the coverage report counts {cov['tests_total']}.")
    L.append(f"  These three counts disagree; the cause is not recorded in the reports (regenerate them together to find out)." if len({files, nref, cov["tests_total"]}) > 1 else "  The three counts agree.")
    L.append(f"- Coverage: language profile {lang['covered']} of {lang['clauses']} normative clauses covered ({pct(lang['covered'], lang['clauses'])}).")
    other = ", ".join(f"{p} {v['covered']} of {v['clauses']}" for p, v in cov["profiles"].items() if p != "language")
    L.append(f"  Other profiles: {other}.")
    L.append(f"- Reference: {ref.get('pass', 0)} pass, {ref.get('fail', 0)} fail of {nref}.")
    em = []
    for a in ("emit-python", "emit-js", "emit-rust"):
        t = tally[a]
        em.append(f"{a[5:]} {t.get('pass', 0)} pass / {t.get('fail', 0)} fail / {t.get('n/a', 0) + t.get('unsupported', 0)} not applicable or unsupported")
    L.append("- Emitters: " + "; ".join(em) + ". Parity with the reference: " + "; ".join(f"{a[5:]} {par['adapters'][a]['agree']} agree, {par['adapters'][a]['disagree']} disagree" for a in ("emit-python", "emit-js", "emit-rust")) + ".")
    t = tally["emit-scala"]
    L.append(f"- Scala emitter: {t.get('pass', 0)} pass, {t.get('fail', 0)} fail, {t.get('unsupported', 0)} unsupported of {len(res['emit-scala']['results'])} results ({par['adapters']['emit-scala']['missing']} tests have no Scala result). Scala does not yet agree with the reference.")
    for a, label in (("wasm-playground", "Wasm playground"), ("lean-core", "Lean core model")):
        t = tally[a]
        L.append(f"- {label}: {t.get('pass', 0)} pass, {t.get('fail', 0)} fail, {t.get('unsupported', 0)} unsupported of {len(res[a]['results'])} results.")
    L.append(f"- Tree-sitter grammar `{ts['tree_sitter_rce']}`: {ts['agree']} of {ts['programs']} programs agree with the reference parser ({len(ts['disagreements'])} disagreements).")
    L.append(f"- Mutation: {mut['sampled']} of {mut['sites']} schema sites sampled (seed {mut['seed']}); {mut['killed']} killed ({mut['kill_rate']}%) on the first run. After survivor-targeted tests: {mut['kill_rate_after_targeted']}%; after round 3: {mut['kill_rate_after_round3']}%; round 4 reports {mut['round4']['kill_rate_counting_133_equivalent']}% counting mutant 133 as equivalent. Survivors are in `reports/mutation.json`.")
    L.append(f"  The mutation baseline (the unmutated mutation build) fails {len(mut['baseline_failures'])} tests; that is not the reference run, which has {ref.get('fail', 0)} failures.")
    return "\n".join(L)


def main():
    readme = ROOT / "README.md"
    s = readme.read_text()
    new = f"{BEGIN}\n{block()}\n{END}"
    if "--print" in sys.argv:
        print(new); return
    if BEGIN in s:
        a, b = s.index(BEGIN), s.index(END) + len(END)
        out = s[:a] + new + s[b:]
    else:
        a = s.index("## Status"); b = s.index("## Convergence notes")
        out = s[:a] + "## Status\n\n" + new + "\n\n" + s[b:]
    if "--check" in sys.argv:
        if out != s:
            sys.exit("README.md status block is stale: run tools/readme_status.py")
        print("README status block is in sync with reports/"); return
    readme.write_text(out)
    print("README.md status block written")


main()
