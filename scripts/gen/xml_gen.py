# Generates tests/text/xml_checks_irp_N.rce: every document of the W3C SCXML
# IRP suite (after confEcma.xsl) read by text.xml must give the same
# canonical dump as lxml (libxml2), the live reference.
import glob, os, sys
from lxml import etree
irp, out = sys.argv[1], sys.argv[2]
def rq(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\t', '\\t').replace('\r', '\\r') + '"'
def canon(e):
    if not isinstance(e.tag, str): return ''
    q = etree.QName(e)
    o = '<{%s}%s' % (q.namespace or '', q.localname)
    for k, v in e.attrib.items():
        o += ' %s=[%s]' % (k, v)
    o += '>'
    if e.text: o += e.text
    for c in e:
        o += canon(c)
        if c.tail: o += c.tail
    return o + '</>'
docs = sorted(glob.glob(irp + '/*/*.scxml'))
cases = []
for f in docs:
    s = open(f).read()
    t = etree.fromstring(s.encode())
    cases.append((os.path.relpath(f, irp), s, canon(t)))
H = open(os.path.join(os.path.dirname(__file__), 'xml_irp_head.rce')).read()
n = 2
for k in range(n):
    with open('%s/xml_checks_irp%d.rce' % (out, k), 'w') as w:
        w.write('# generated by scripts/gen/xml_gen.py; do not edit\n' + H)
        for (f, s, c) in cases[k::n]:
            w.write('# %s\ncheck xcanon(%s) == %s\n' % (f, rq(s), rq(c)))
print(len(cases))
