# "# ---- cptab" markers): one 256-character text per row, rows 0..255
# for the BMP (surrogate rows hold U+FFFD and are never read) and rows
# 256..271 for U+1F000..U+1FFFF (symbols and emoji). rce 0.1.3 has no
# text-from-code-point built-in, so decoding a \u escape or a
# percent-encoded UTF-8 sequence looks the character up here.
import sys, unicodedata
def lit(cp):
    if 0xD800 <= cp <= 0xDFFF:
        cp = 0xFFFD
    c = chr(cp)
    if c in '"\\' or unicodedata.category(c)[0] not in 'LMNPS' or c == '\u2028':
        return '\\u{%x}' % cp
    return c
rows = [r * 256 for r in range(256)] + [0x1F000 + r * 256 for r in range(16)]
out = ['# ---- cptab (generated by scripts/gen/cptab.py; do not edit)', 'const CPTAB: List[text] = [']
for i, base in enumerate(rows):
    out.append('    "' + ''.join(lit(base + k) for k in range(256)) + '"' + (',' if i < len(rows) - 1 else ''))
out.append(']')
out.append('# ---- cptab end')
path = sys.argv[1]
src = open(path).read()
a = src.index('# ---- cptab'); b = src.index('# ---- cptab end') + len('# ---- cptab end')
open(path, 'w').write(src[:a] + '\n'.join(out) + src[b:])
