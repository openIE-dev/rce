def resp(b, i=0):
    t = b[i:i + 1]; j = b.index(b'\r\n', i); h = b[i + 1:j].decode(); k = j + 2
    def bv(x):
        try:
            s = x.decode('utf-8')
            if any(0xd800 <= ord(ch) <= 0xdfff for ch in s) or any(ord(ch) >= 0x10000 and not 0x1f000 <= ord(ch) < 0x20000 for ch in s): raise ValueError
            return s
        except (UnicodeDecodeError, ValueError): return {'b': x.hex()}
    if t == b'+': return {'s': h}, k
    if t == b'-': return {'err': h}, k
    if t in (b':', b',', b'('): return Num(h), k
    if t == b'_': return None, k
    if t == b'#': return h == 't', k
    if t in (b'$', b'=', b'!'):
        n = int(h)
        if n < 0: return None, k
        x = b[k:k + n]
        if t == b'=': x = x[4:]
        v = bv(x)
        return ({'err': v} if t == b'!' else v), k + n + 2
    if t in (b'*', b'~', b'>', b'%', b'|'):
        n = int(h)
        if n < 0: return None, k
        xs = []
        for _ in range(n * 2 if t in (b'%', b'|') else n):
            v, k = resp(b, k); xs.append(v)
        if t == b'|': return resp(b, k)
        if t == b'~': return {'set': xs}, k
        if t == b'>': return {'push': xs}, k
        if t == b'%': return {'map': xs}, k
        return xs, k
    raise ValueError(t)
