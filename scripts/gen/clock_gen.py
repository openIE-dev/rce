assert hashlib.sha256(data).hexdigest() == SHA, 'rust_core_time_tests.rs changed'
src = data.decode()

I64MAX = 2**63 - 1
SKIP = {'div_duration_f32', 'div_duration_f64', 'duration_const', 'from_neg_zero'}

H = '''
# ---- generated by scripts/gen/clock_gen.py; Dur? models a Rust value that
# may panic (none = panicked).
fn N(s: i64, n: i64) -> Dur?
    let r = dur_new(s, n) catch Dur(secs: -1, nanos: 0)
    return if r.secs < 0 then none else some(r)
fn fr(r: Dur) -> Dur? = if r.secs < 0 then none else some(r)
fn Fsecs(n: i64) -> Dur? = fr(from_secs(n) catch Dur(secs: -1, nanos: 0))
fn Fmillis(n: i64) -> Dur? = fr(from_millis(n) catch Dur(secs: -1, nanos: 0))
fn Fmicros(n: i64) -> Dur? = fr(from_micros(n) catch Dur(secs: -1, nanos: 0))
fn Fnanos(n: i64) -> Dur? = fr(from_nanos(n) catch Dur(secs: -1, nanos: 0))
fn Fmins(n: i64) -> Dur? = fr(from_mins(n) catch Dur(secs: -1, nanos: 0))
fn Fhours(n: i64) -> Dur? = fr(from_hours(n) catch Dur(secs: -1, nanos: 0))
fn Fdays(n: i64) -> Dur? = fr(from_days(n) catch Dur(secs: -1, nanos: 0))
fn Fweeks(n: i64) -> Dur? = fr(from_weeks(n) catch Dur(secs: -1, nanos: 0))
fn dk(d: Dur?) -> text
    match d
        some(x) -> return x.secs.tostr() + "." + x.nanos.tostr()
        none -> return "none"
fn G(d: Dur?) -> Dur = d.or(Dur(secs: -1, nanos: -1))
fn bad(d: Dur?) -> bool = G(d).secs < 0
fn Oadd(a: Dur?, b: Dur?) -> Dur?
    if bad(copy(a)) or bad(copy(b))
        return none
    let x = G(a)
    let y = G(b)
    return checked_add(&x, &y)
fn Osub(a: Dur?, b: Dur?) -> Dur?
    if bad(copy(a)) or bad(copy(b))
        return none
    let x = G(a)
    let y = G(b)
    return checked_sub(&x, &y)
fn Osatadd(a: Dur?, b: Dur?) -> Dur?
    if bad(copy(a)) or bad(copy(b))
        return none
    let x = G(a)
    let y = G(b)
    return some(saturating_add(&x, &y))
fn Osatsub(a: Dur?, b: Dur?) -> Dur?
    if bad(copy(a)) or bad(copy(b))
        return none
    let x = G(a)
    let y = G(b)
    return some(saturating_sub(&x, &y))
fn Oabs(a: Dur?, b: Dur?) -> Dur?
    if bad(copy(a)) or bad(copy(b))
        return none
    let x = G(a)
    let y = G(b)
    return some(abs_diff(&x, &y))
fn Omul(a: Dur?, k: i64) -> Dur?
    if bad(copy(a))
        return none
    let x = G(a)
    return checked_mul(&x, k)
fn Osatmul(a: Dur?, k: i64) -> Dur?
    if bad(copy(a))
        return none
    let x = G(a)
    return some(saturating_mul(&x, k))
fn Odiv(a: Dur?, k: i64) -> Dur?
    if bad(copy(a))
        return none
    let x = G(a)
    return checked_div(&x, k)
fn Isecs(a: Dur?) -> i64 = G(a).secs
fn Imillis(a: Dur?) -> i64
    let x = G(a)
    return subsec_millis(&x)
fn Imicros(a: Dur?) -> i64
    let x = G(a)
    return subsec_micros(&x)
fn Inanos(a: Dur?) -> i64
    let x = G(a)
    return subsec_nanos(&x)
fn Osum(ds: List[Dur?]) -> Dur?
    var xs: List[Dur] = []
    for d in ds
        if bad(copy(d))
            return none
        xs.push(G(copy(d)))
    return dur_sum(&xs)
fn fm(a: Dur?, prec: i64, width: i64, al: text, plus: bool) -> text
    let x = G(a)
    return dur_debug_with(&x, prec, width, &al, plus)
'''

CONST = {'ZERO': 'N(0, 0)', 'MAX': 'N(%d, 999999999)' % I64MAX, 'SECOND': 'N(1, 0)',
         'NANOSECOND': 'N(0, 1)', 'MILLISECOND': 'N(0, 1000000)', 'MICROSECOND': 'N(0, 1000)'}

def num(t):
    t = t.replace('_', '')
    v = I64MAX if t == 'u64::MAX' else int(t)
    return v

class P:
    def __init__(s, text):
        text = re.sub(r'\bas u(128|64|32)\b', '', text)
        s.toks = re.findall(r'"(?:[^"\\]|\\.)*"|u64::MAX|Duration::\w+|\d[\d_]*|\w+|::|[()+\-*/,.\[\]]', text)
        s.i = 0
    def peek(s):
        return s.toks[s.i] if s.i < len(s.toks) else None
    def eat(s, t=None):
        x = s.toks[s.i]; s.i += 1
        assert t is None or x == t, (t, x, s.toks)
        return x
    def expr(s):
        a = s.term()
        while s.peek() in ('+', '-'):
            op = s.eat(); b = s.term()
            a = binop(op, a, b)
        return a
    def term(s):
        a = s.unary()
        while s.peek() in ('*', '/'):
            op = s.eat(); b = s.unary()
            a = binop(op, a, b)
        return a
    def unary(s):
        a = s.atom()
        while s.peek() == '.':
            s.eat('.'); m = s.eat(); s.eat('(')
            args = []
            while s.peek() != ')':
                args.append(s.expr())
                if s.peek() == ',': s.eat()
            s.eat(')')
            a = method(a, m, args)
        return a
    def atom(s):
        t = s.eat()
        if t == '(':
            a = s.expr(); s.eat(')'); return a
        if t.startswith('Duration::'):
            name = t[10:]
            if name in CONST:
                return ('D', CONST[name])
            s.eat('(')
            args = []
            while s.peek() != ')':
                args.append(s.expr())
                if s.peek() == ',': s.eat()
            s.eat(')')
            if name == 'new':
                return ('D', 'N(%s, %s)' % (args[0][1], args[1][1]))
            if name == 'from_nanos_u128':
                name = 'from_nanos'
                if int(args[0][1]) > I64MAX:
                    # beyond an i64 of nanoseconds: not representable, refused
                    return ('D', 'none')
            return ('D', 'F%s(%s)' % (name[5:], args[0][1]))
        if t == 'Some':
            s.eat('('); a = s.expr(); s.eat(')'); return ('D', a[1])
        if t == 'None':
            return ('D', 'none')
        if t == 'u64::MAX' or t[0].isdigit():
            return ('I', str(num(t)))
        raise ValueError('atom ' + t)

def binop(op, a, b):
    if a[0] == 'I' and b[0] == 'I':
        return ('I', str(eval('%s %s %s' % (a[1], op.replace('/', '//'), b[1]))))
    if op == '+': return ('D', 'Oadd(%s, %s)' % (a[1], b[1]))
    if op == '-': return ('D', 'Osub(%s, %s)' % (a[1], b[1]))
    if op == '*': return ('D', 'Omul(%s, %s)' % (a[1], b[1]))
    if op == '/': return ('D', 'Odiv(%s, %s)' % (a[1], b[1]))

def method(a, m, args):
    M = {'checked_add': 'Oadd', 'checked_sub': 'Osub', 'saturating_add': 'Osatadd', 'saturating_sub': 'Osatsub',
         'abs_diff': 'Oabs', 'checked_mul': 'Omul', 'saturating_mul': 'Osatmul', 'checked_div': 'Odiv'}
    if m in M:
        return ('D', '%s(%s, %s)' % (M[m], a[1], args[0][1]))
    if m == 'as_secs': return ('I', 'Isecs(%s)' % a[1])
    if m.startswith('subsec_'): return ('I', 'I%s(%s)' % (m[7:], a[1]))
    raise ValueError(m)

def fmt(spec, arg):
    m = re.fullmatch(r'\{:([<>^])?(\+)?(\d+)?(?:\.(\d+))?\?\}', spec)
    assert m, spec
    al, plus, w, p = m.groups()
    if w and CUR == 'debug_formatting_extreme_values':
        w = str(int(w) - 1)  # i64::MAX + 1 prints one digit shorter than u64::MAX + 1
    return ('T', 'fm(%s, %s, %s, "%s", %s)' % (arg[1], p if p else -1, w if w else -1, al or '', 'true' if plus else 'false'))

def side(text):
    text = text.strip()
    m = re.fullmatch(r'format!\(\s*("[^"]*")\s*,(.*)\)', text, re.S)
    if m:
        p = P(m.group(2)); a = p.expr(); assert p.peek() is None
        return fmt(m.group(1)[1:-1], a)
    if text.startswith('"'):
        s = text[1:-1]
        s = s.replace(str(2**64), str(2**63)).replace(str(2**64 - 1), str(I64MAX))
        return ('T', '"%s"' % s)
    if text.startswith('durations.iter().sum'):
        return ('D', 'Osum(DURS)')
    p = P(text); a = p.expr(); assert p.peek() is None, (text, p.toks[p.i:])
    return a

def split_args(s):
    out, depth, cur, q = [], 0, '', False
    for c in s:
        if c == '"': q = not q
        if not q and c in '([': depth += 1
        if not q and c in ')]': depth -= 1
        if not q and c == ',' and depth == 0:
            out.append(cur); cur = ''
        else:
            cur += c
    out.append(cur)
    return [x for x in out if x.strip()]

def cmpv(a, b, eq=True):
    op = '==' if eq else '!='
    if a[0] == 'D' or b[0] == 'D':
        return 'check dk(%s) %s dk(%s)' % (a[1], op, b[1])
    return 'check %s %s %s' % (a[1], op, b[1])

out = [H]
CUR = ''
n = 0
tests = re.split(r'\n#\[test\]\n', src)[1:]
skipped = []
for t in tests:
    panic = t.startswith('#[should_panic]')
    name = re.search(r'fn (\w+)\(', t).group(1)
    if name in SKIP or re.search(r'f32|f64|\d\.\d', re.sub(r'"[^"]*"', '', t)):
        skipped.append(name); continue
    body = t[t.index('{') + 1:t.rindex('}')]
    body = re.sub(r'//[^\n]*', '', body)
    out.append('# %s' % name)
    CUR = name
    if panic:
        lets = dict(re.findall(r'let (\w+)(?:: \w+)? = ([^;]*);', body))
        last = re.findall(r'let _ = ([^;]*);', body)[0]
        for _ in range(3):
            for k, v in lets.items():
                if k != '_':
                    last = re.sub(r'\b%s\b' % k, '(%s)' % v, last)
        a = side(last)
        out.append('check dk(%s) == "none"' % a[1]); n += 1
        continue
    if 'durations' in body:
        items = re.search(r'\[(.*?)\];', body, re.S).group(1)
        ds = [side(x)[1] for x in split_args(items)]
        out.append('let DURS: List[Dur?] = [%s]' % ', '.join(ds))
        body = body[body.index('let sum'):]
        body = body.replace('let sum = durations.iter().sum::<Duration>();', '')
        body = body.replace('assert_eq!(sum,', 'assert_eq!(durations.iter().sum::<Duration>(),')
    for kind, args in re.findall(r'(assert_eq|assert_ne|assert)!\((.*?)\);', body, re.S):
        parts = split_args(args)
        if kind == 'assert':
            raise ValueError(args)
        a, b = side(parts[0]), side(parts[1])
        out.append(cmpv(a, b, kind == 'assert_eq')); n += 1

# DURS as a let at module level is not allowed: wrap correct_sum in a fn.
txt = '\n'.join(out)
txt = re.sub(r'let DURS: List\[Dur\?\] = (\[.*?\])\n(check .*)', lambda m: 'fn durs() -> List[Dur?] = %s\n%s' % (m.group(1), m.group(2).replace('DURS', 'durs()')), txt)
