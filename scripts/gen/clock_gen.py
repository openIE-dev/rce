"""Generate tests/os/clock_checks.rce for lib/os/clock.rce.

Official: vectors/os/rust_core_time_tests.rs (rust-lang/rust
8a9dd7abdf013ec10cfeaaa3685feba18ef1c90c, library/coretests/tests/time.rs).
Every integer assert_eq!/assert_ne!/assert! and every #[should_panic] test
in the Duration tests is translated mechanically; float tests are skipped.
Range adaptation: Dur secs are i64, so u64::MAX becomes i64::MAX and the
printed u64::MAX (+1) in the extreme formatting tests becomes i64::MAX (+1).
Then scripts/gen/clock_derived.rce is appended (derived checks for
Timespec, wasi-clocks values, Mono admission and timers).
"""
