# Generates tests/ui/states_checks_irpN.rce: every test of the W3C SCXML
# IRP suite (vectors/ui/scxml-irp-full: the .txml files after the suite's
# own confEcma.xsl, see scripts/gen/irp_xslt.py) must reach its "pass"
# final state. Manual tests (manifest manual="true") get the check their
# description asks of the tester, written out next to each.
import glob, os, re, sys
d, out = sys.argv[1], sys.argv[2]
per = int(sys.argv[3]) if len(sys.argv) > 3 else 12
man = open(d + '/manifest.xml').read()
tests = []
for m in re.finditer(r'<test id="(\d+)" conformance="(\w+)" manual="(\w+)"\s*>\s*<start uri="([^"]+)"/>', man):
    tests.append((m.group(1), m.group(2), m.group(3) == 'true', m.group(4)))
def rq(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\t', '\\t').replace('\r', '\\r') + '"'
MANUAL = {
 # halts on entering the top-level final state: event1 (raised there) is never taken
 '415': ('irp_trace', '+final,-final'),
 # the document must be rejected (its script cannot be fetched)
 '301': ('irp', 'err script src not found'),
 # both cases (a late-bound variable before binding, a missing substructure) yield undefined without an error
 '307': ('irp_logs', 'entering s0 value of Var 1 is: :undefined|no error in s0:|entering s1, value of non-existent substructure of Var 1 is: :undefined|No error in s1:'),
 '313': ('irp', 'pass'), '314': ('irp', 'pass'),
 # both key/value pairs reach the target (the raw message keeps both)
 '178': ('irp_logs', '_event :Var1=2&Var1=3'),
 # the autoforwarded event has the same fields in the child as in the parent
 '230': ('irp_same', ''),
 # the cancelled child runs its onexit handlers, and never reaches its final state
 '250': ('irp_logs', 'Exiting sub01|Exiting sub0'),
}
cases = []
for (tid, conf, manual, uri) in tests:
    dd = os.path.join(d, os.path.dirname(uri))
    main = os.path.join(d, uri[:-5] + '.scxml')
    if tid == '513':
        # fully manual (test513.txt): POST a well-formed event, as its wget
        # does, to the processor's location and expect 200; the receiving
        # document (ours) passes when it gets that event with its fields
        doc = ('<scxml xmlns="http://www.w3.org/2005/07/scxml" version="1.0" datamodel="ecmascript" initial="s0">'
               '<state id="s0"><transition event="test" cond="_event.data.key1 == \'value1\' &amp;&amp; _event.data.key2 == \'value2\'" target="pass"/>'
               '<transition event="*" target="fail"/></state><final id="pass"/><final id="fail"/></scxml>')
        req = ('POST /s0/basichttp HTTP/1.1\r\nHost: scxml.local\r\n_scxmleventname: test\r\n'
               'Content-Type: application/x-www-form-urlencoded\r\nContent-Length: 23\r\n\r\nkey1=value1&key2=value2')
        cases.append((tid, conf, uri, 'irp_http', doc, ['request'], [req], '200 OK|pass')); continue
    if not os.path.exists(main):
        print('skip (no document)', uri); continue
    names, bodies = [], []
    for f in sorted(os.listdir(dd)):
        p = os.path.join(dd, f)
        if f.endswith('.scxml') and p != main and 'sub' in f: names.append(f); bodies.append(open(p).read())
        elif f.endswith('.txt'): names.append(f); bodies.append(open(p).read())
    if manual and tid not in MANUAL:
        print('manual test without a check:', tid); continue
    fn, exp = MANUAL.get(tid, ('irp', 'pass')) if manual or tid in ('313', '314') else ('irp', 'pass')
    cases.append((tid, conf, uri, fn, open(main).read(), names, bodies, exp))
H = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'irp_head.rce')).read()
for f in glob.glob(out + '/states_checks_irp*.rce'): os.remove(f)
for k in range(0, len(cases), per):
    with open('%s/states_checks_irp%02d.rce' % (out, k // per), 'w') as w:
        w.write('# generated by scripts/gen/irp_gen.py; do not edit\n' + H)
        for (tid, conf, uri, fn, doc, names, bodies, exp) in cases[k:k + per]:
            w.write('# %s (%s)\n' % (uri, conf))
            w.write('check %s(%s, [%s], [%s]) == %s\n' % (fn, rq(doc), ', '.join(rq(n) for n in names), ', '.join(rq(b) for b in bodies), rq(exp)))
print(len(cases), 'tests in', (len(cases) + per - 1) // per, 'files')
