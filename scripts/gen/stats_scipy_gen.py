#!/usr/bin/env python3
"""Generate tests/num/stats_checks_ref_*.rce: num.stats against SciPy 1.18.1
and NumPy 2.5.4 (scipy.stats distributions and tests, numpy.quantile),
and the seeded variates against an independent RFC 8439 ChaCha20.

Distribution values are checked by relative error against SciPy with a
tolerance per family (REL below); quantiles are bit for bit against
numpy.quantile; test statistics and p-values by relative error.

Run with the SciPy venv python. Usage: stats_scipy_gen.py [--measure] [--out DIR]
"""
import os, struct, sys
import numpy as np
import scipy
from scipy import stats as S, special as SP

assert scipy.__version__ == '1.18.1' and np.__version__ == '2.5.4'

def f(x): return repr(float(x))
def lst(xs): return '[' + ', '.join(f(x) for x in xs) + ']'

HEAD = '''# generated by scripts/gen/stats_scipy_gen.py: %s

fn stx_rel(q: f64, c: f64) -> f64 = if q == c then 0.0 else st_abs(q - c) / st_abs(c)
'''

# ---------------------------------------------------------------- distributions
X_T = [-40.0, -12.5, -3.0, -1.0, -0.25, 0.1, 0.5, 1.5, 2.0, 4.0, 9.0, 30.0]
