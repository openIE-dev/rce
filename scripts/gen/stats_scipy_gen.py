# ---------------------------------------------------------------- variates
def rotl(v, n): return ((v << n) | (v >> (32 - n))) & 0xffffffff
def qr(s, a, b, c, d):
    s[a] = (s[a] + s[b]) & 0xffffffff; s[d] = rotl(s[d] ^ s[a], 16)
    s[c] = (s[c] + s[d]) & 0xffffffff; s[b] = rotl(s[b] ^ s[c], 12)
    s[a] = (s[a] + s[b]) & 0xffffffff; s[d] = rotl(s[d] ^ s[a], 8)
    s[c] = (s[c] + s[d]) & 0xffffffff; s[b] = rotl(s[b] ^ s[c], 7)
def block(key, ctr, nonce):
    s = [0x61707865, 0x3320646e, 0x79622d32, 0x6b206574] + list(struct.unpack('<8I', key)) + [ctr] + list(struct.unpack('<3I', nonce))
    w = s[:]
    for _ in range(10):
        qr(w, 0, 4, 8, 12); qr(w, 1, 5, 9, 13); qr(w, 2, 6, 10, 14); qr(w, 3, 7, 11, 15)
        qr(w, 0, 5, 10, 15); qr(w, 1, 6, 11, 12); qr(w, 2, 7, 8, 13); qr(w, 3, 4, 9, 14)
    return [(w[i] + s[i]) & 0xffffffff for i in range(16)]
# RFC 8439 2.3.2 test vector
assert block(bytes(range(32)), 1, bytes.fromhex('000000090000004a00000000'))[0] == 0xe4e7f110

class Gen:
    def __init__(s, seed, stream): s.key = bytes(seed); s.stream = stream; s.blk = 0; s.buf = []; s.pos = 16
    def u32(s):
        if s.pos >= 16:
            s.buf = block(s.key, s.blk & 0xffffffff, struct.pack('<3I', s.stream & 0xffffffff, s.stream >> 32, s.blk >> 32)); s.blk += 1; s.pos = 0
        v = s.buf[s.pos]; s.pos += 1; return v
    def bits(s, k):
        if k <= 32: return s.u32() >> (32 - k)
        hi = s.u32() >> (64 - k); lo = s.u32(); return (hi << 32) | lo

def variate_lines():
    seed = [(7 * i + 3) % 256 for i in range(32)]
    g = Gen(seed, 5)
    us, uo, ns, es = [], [], [], []
    for _ in range(40): us.append(g.bits(53) * 2.0 ** -53)
    for _ in range(40): uo.append((g.bits(52) + 0.5) * 2.0 ** -52)
    for _ in range(40): ns.append(1.5 + 2.0 * float(SP.ndtri((g.bits(52) + 0.5) * 2.0 ** -52)))
    for _ in range(40): es.append(-3.0 * float(np.log((g.bits(52) + 0.5) * 2.0 ** -52)))
    g = Gen(seed, 5)
    ks = [g.bits(53) for _ in range(40)] + [g.bits(52) for _ in range(120)]
    out = ['''# the draws of a rand.det generator seeded with %s, stream 5
# (det.bits(r, 53) x 40 then det.bits(r, 52) x 120), from an independent
# Python ChaCha20
const STK: List[i64] = %s

fn stx_draws() -> List[f64]
    var v: List[f64] = []
    for i in 0..40
        v.push(uniform(STK[i]))
    for i in 40..80
        v.push(uniform_open(STK[i]))
    for i in 80..120
        v.push(normal(STK[i], 1.5, 2.0))
    for i in 120..160
        v.push(exponential(STK[i], 3.0))
    return v

const STV: List[f64] = stx_draws()
''' % (seed, '[' + ', '.join(str(k) for k in ks) + ']')]
    for i, u in enumerate(us + uo):
        out.append('check STV[%d] == %s  # k / 2^53 of the RFC 8439 keystream draw' % (i, f(u)))
    for i, v in enumerate(ns):
        out.append('check stx_rel(STV[%d], %s) <= 1.0e-14  # 1.5 + 2 scipy.special.ndtri(u)' % (80 + i, f(v)))
    for i, v in enumerate(es):
        out.append('check stx_rel(STV[%d], %s) <= 4.0e-16  # -3 numpy.log(u)' % (120 + i, f(v)))
    return out

def main():
    measure = '--measure' in sys.argv
    outdir = sys.argv[sys.argv.index('--out') + 1] if '--out' in sys.argv else 'tests/num'
    shards = []
    dc = dist_cases()
    # comptime fuel is per file: a quantile (bracketing and bisection over
    # the cdf) costs about as much as W direct evaluations, a beta or F
    # quantile (continued fractions near 1) about 3 W
    W, BUDGET = 8, 48
    groups, cur, cost = [], [], 0
    for t in dc:
        w = 1
        if '_ppf(' in t[0] or '_isf(' in t[0]:
            w = 3 * W if t[2] == 'betaq' else W
        if cur and cost + w > BUDGET:
            groups.append(cur); cur, cost = [], 0
        cur.append(t); cost += w
    groups.append(cur)
    for part in groups:
        i = dc.index(part[0])
        sh = [HEAD % 'scipy.stats 1.18.1 distributions (pdf/cdf/sf/ppf), relative error per family']
        if measure:
            sh.append('const M_%d: List[f64] = [%s]' % (i, ', '.join(
                ('((%s) catch -1) as f64 - %s' % (e, f(v))) if fam == 'int' else 'stx_rel(%s catch -1.0, %s)' % (e, f(v))
                for e, v, fam in part)))
        else:
            for e, v, fam in part:
                if fam == 'int':
                    sh.append('check (%s catch -1) == %d  # scipy.stats %s' % (e, v, e.split('(')[0]))
                else:
                    src = 'mpmath 1.4.1' if fam == 'norm' else 'scipy.stats'
                    sh.append('check stx_rel(%s catch -1.0, %s) <= %s  # %s %s' % (e, f(v), repr(REL[fam]), src, e.split('(')[0]))
        shards.append(sh)
    shards.append([HEAD % 'numpy.quantile 2.5.4 methods 1-9 (Hyndman-Fan), bit for bit', 'const STX_Q: List[f64] = ' + lst(QDATA), ''] + quant_cases())
    tc = test_cases()
    sh = [HEAD % 'scipy.stats 1.18.1 hypothesis tests, moments', 'const STA: List[f64] = ' + lst(A),
          'const STB: List[f64] = ' + lst(B), 'const STB10: List[f64] = ' + lst(B10)]
    sh += [e for e, v, l in tc if v is None]
    tc = [t for t in tc if t[1] is not None]
    if measure:
        sh.append('const M_T: List[f64] = [%s]' % ', '.join('stx_rel(%s, %s)' % (e, f(v)) for e, v, l in tc))
    else:
        sh += ['check stx_rel(%s, %s) <= 1.0e-12  # %s' % (e, f(v), l) for e, v, l in tc]
    shards.append(sh)
    shards.append([HEAD % 'seeded variates vs an independent RFC 8439 ChaCha20 (rand.det stream layout)'] + variate_lines())
    for i, sh in enumerate(shards):
        open(os.path.join(outdir, 'stats_checks_ref_%02d.rce' % i), 'w').write('\n'.join(sh) + '\n')
    print(len(shards), 'shards')

if __name__ == '__main__':
    main()
