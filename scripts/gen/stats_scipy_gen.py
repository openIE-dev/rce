UNIT = [1e-12, 1e-5, 0.01, 0.1, 0.3, 0.5, 0.77, 0.95, 0.999, 1.0 - 1e-9]

def dist_cases():
    c = []  # (expr, value, family)
    for x in X_T + [-38.0, 8.0, 20.0]:
        c.append(('norm_pdf(%s, 0.0, 1.0)' % f(x), mp_norm('pdf', x), 'norm'))
