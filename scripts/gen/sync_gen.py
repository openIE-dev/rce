# ---------- derived: mutation log laws (Replicache push/pull semantics) ----------
def rmut(st, name, key, arg):
    st = dict(st)
    if name == 'put': st[key] = arg
    elif name == 'del': st.pop(key, None)
    elif name == 'incr':
        cur = st.get(key, 0)
        if isinstance(cur, int) and not isinstance(cur, bool) and isinstance(arg, int): st[key] = cur + arg
    return st
def rcmodel(script):
    db, lm, log = {}, {}, []
    cl = {c: {'base': {}, 'pend': [], 'next': 1} for c in ['c1', 'c2', 'c3']}
    for line in script:
        f = line.split('|'); c = cl[f[1]]
        if f[0] == 'm':
            c['pend'].append((c['next'], f[2], f[3], json.loads(f[4]))); c['next'] += 1
        elif f[0] == 'push':
            for (i, n, k, a) in c['pend']:
                last = lm.get(f[1], 0)
                if i > last + 1: break
                if i == last + 1: db = rmut(db, n, k, a); lm[f[1]] = i; log.append((n, k, a))
        elif f[0] == 'pull':
            c['base'] = dict(db); c['pend'] = [m for m in c['pend'] if m[0] > lm.get(f[1], 0)]
    def cj(d): return canon(loads(json.dumps(d)))
    o = cj(db) + ' replay=db'
    for k in ['c1', 'c2', 'c3']:
        v = cl[k]['base']
        for (i, n, kk, a) in cl[k]['pend']: v = rmut(v, n, kk, a)
        o += ' %s/%d' % (cj(v), len(cl[k]['pend']))
    return o
