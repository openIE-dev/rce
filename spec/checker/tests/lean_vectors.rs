//! Test vectors linking the reference evaluator to the Lean small-step
//! semantics (spec/lean/RCE/ParSem.lean). Random well-formed core programs
//! (assignments, sequencing, `if a < b`, two-branch `par` with disjoint
//! footprints, small integers) are admitted by the checker and run by
//! `conc::run_main`; each final value becomes a Lean theorem in
//! spec/lean/RCE/ParVectors.lean, stating that every complete small-step
//! interleaving of the same program ends with that value (`vector_sound`,
//! via `par_det`). The file must match what this test generates
//! (RCE_BLESS=1 rewrites it); `lake build` checks the theorems.
use rce_spec_check::conc::{Outcome, RunCfg, run_main};
use rce_spec_check::parse::parse;

const NV: usize = 5;
const NPROG: usize = 40;
/// at least this many overflow (trap) vectors
const NTRAP: usize = 6;

struct Rng(u64);
impl Rng {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
        self.0 >> 33
    }
    fn below(&mut self, n: u64) -> u64 {
        self.next() % n
    }
}

/// (rce source, lean term)
type Pair = (String, String);

/// These vectors compare the verdict of one property (session linearity, priorities, the parallel
/// semantics) with the Lean model. Hygiene findings (unread names, dead stores, discarded values)
/// are a different property of the same one language, so they are set aside before comparing.
fn property_verdict(r: &Result<(), String>) -> Result<(), String> {
    let Err(e) = r else { return Ok(()) };
    let kept: Vec<&str> = e
        .split("; line ")
        .filter(|f| !["W-UNUSED-1", "W-UNUSED-2", "W-ASSIGN-1", "W-DROP-1"].iter().any(|h| f.contains(h)))
        .collect();
    if kept.is_empty() { Ok(()) } else { Err(kept.join("; line ")) }
}

fn expr(r: &mut Rng, rd: &[usize], d: u32) -> Pair {
    let k = if d == 0 { r.below(2) } else { r.below(4) };
    match k {
        0 => {
            let n = r.below(10);
            (n.to_string(), format!("(.lit {n})"))
        }
        1 if !rd.is_empty() => {
            let v = rd[r.below(rd.len() as u64) as usize];
            (format!("v{v}"), format!("(.var {v})"))
        }
        1 => ("1".into(), "(.lit 1)".into()),
        2 => {
            let (a, la) = expr(r, rd, d - 1);
            let (b, lb) = expr(r, rd, d - 1);
            (format!("({a} + {b})"), format!("(.add {la} {lb})"))
        }
        _ => {
            let (a, la) = expr(r, rd, d - 1);
            let (b, lb) = expr(r, rd, d - 1);
            (format!("({a} * {b})"), format!("(.mul {la} {lb})"))
        }
    }
}

/// a statement block at indent `ind`, writing only `wr`, reading `rd`
fn block(r: &mut Rng, wr: &[usize], rd: &[usize], ind: usize, d: u32) -> Pair {
    let n = 1 + r.below(3);
    let mut src = String::new();
    let mut lean: Option<String> = None;
    for _ in 0..n {
        let (s, l) = stmt(r, wr, rd, ind, d);
        src += &s;
        lean = Some(match lean {
            None => l,
            Some(p) => format!("(.seq {p} {l})"),
        });
    }
    (src, lean.unwrap())
}

fn stmt(r: &mut Rng, wr: &[usize], rd: &[usize], ind: usize, d: u32) -> Pair {
    let pad = "    ".repeat(ind);
    let k = if d == 0 { 0 } else { r.below(4) };
    match k {
        1 => {
            let (a, la) = expr(r, rd, 1);
            let (b, lb) = expr(r, rd, 1);
            let (t, lt) = block(r, wr, rd, ind + 1, d - 1);
            let (e, le) = block(r, wr, rd, ind + 1, d - 1);
            (
                format!("{pad}if {a} < {b}\n{t}{pad}else\n{e}"),
                format!("(.ite (.lt {la} {lb}) {lt} {le})"),
            )
        }
        2 | 3 if wr.len() >= 2 => {
            // split the writable set; both branches may read what neither writes
            let mut a = vec![];
            let mut b = vec![];
            for (i, &v) in wr.iter().enumerate() {
                if i == 0 || (i > 1 && r.below(2) == 0) { a.push(v) } else { b.push(v) }
            }
            let shared: Vec<usize> = rd.iter().copied().filter(|v| !wr.contains(v)).collect();
            let ra: Vec<usize> = a.iter().chain(shared.iter()).copied().collect();
            let rb: Vec<usize> = b.iter().chain(shared.iter()).copied().collect();
            let (sa, la) = block(r, &a, &ra, ind + 2, d - 1);
            let (sb, lb) = block(r, &b, &rb, ind + 2, d - 1);
            (
                format!("{pad}par\n{pad}    branch a\n{sa}{pad}    branch b\n{sb}"),
                format!("(.par {la} {lb})"),
            )
        }
        _ => {
            let x = wr[r.below(wr.len() as u64) as usize];
            let (e, le) = expr(r, rd, 2);
            (format!("{pad}v{x} = {e}\n"), format!("(.assign {x} {le})"))
        }
    }
}

fn generate() -> String {
    let mut r = Rng(0x5eed_0f_ce11);
    let mut out = String::from(
        "import RCE.ParCheck\nimport RCE.ParRefine\n/-! Generated by spec/checker/tests/lean_vectors.rs (RCE_BLESS=1). Each\n    theorem: the reference evaluator's final value of a variable, for a\n    random W-PAR-1 core program, holds after every complete small-step\n    interleaving and is the value of the bounded evaluator model `evalB`;\n    programs on which the Rust evaluator traps with an i64 overflow are\n    trap vectors (`evalB = none`). Do not edit by hand. -/\nnamespace RCE.ParVectors\nopen RCE.ParSem\nset_option maxRecDepth 20000\n",
    );
    let all: Vec<usize> = (0..NV).collect();
    let mut p = 0;
    let mut skipped = 0;
    while p < NPROG || skipped < NTRAP {
        let init: Vec<u64> = (0..NV).map(|_| r.below(10)).collect();
        let (body, lean) = block(&mut r, &all, &all, 1, 3);
        let mut src = String::from("fn main()\n");
        for (i, v) in init.iter().enumerate() {
            src += &format!("    var v{i}: i64 = {v}\n");
        }
        src += &body;
        for i in 0..NV {
            src += &format!("    emit v{i}\n");
        }
        let d = rce_spec_check::check_program(&[("t.rce".into(), src.clone())], false);
        assert!(property_verdict(&d[0].1).is_ok(), "not admitted: {:?}\n{src}", d[0].1);
        let m = parse(&src).unwrap();
        let res = run_main(&m, &RunCfg::default()).unwrap();
        // i64 overflow traps in the evaluator; ParSem has unbounded
        // integers, so such programs become trap vectors for the bounded
        // evaluator model `evalB` (ParRefine.lean) instead
        if let Outcome::Stopped(e) = &res.outcome && e.contains("overflow") {
            if skipped >= NTRAP {
                continue;
            }
            let inits: Vec<String> = init.iter().map(|v| v.to_string()).collect();
            out += &format!(
                "\n/-\n{src}-/\ndef o{skipped} : St := {lean}\ndef so{skipped} : Store := st0 [{}]\ntheorem o{skipped}_wf : WFb o{skipped} = true := by decide\ntheorem o{skipped}_trap : (evalB o{skipped} so{skipped}).isNone = true := by decide\n",
                inits.join(", ")
            );
            skipped += 1;
            continue;
        }
        assert!(matches!(res.outcome, Outcome::Done), "{:?}\n{src}", res.outcome);
        if p >= NPROG {
            continue;
        }
        let vals: Vec<String> = res.outputs.iter().map(|x| x.show()).collect();
        assert_eq!(vals.len(), NV);
        let inits: Vec<String> = init.iter().map(|v| v.to_string()).collect();
        out += &format!("\n/-\n{src}-/\ndef p{p} : St := {lean}\ndef s{p} : Store := st0 [{}]\n", inits.join(", "));
        for (i, v) in vals.iter().enumerate() {
            let lv = if v.starts_with('-') { format!("({v})") } else { v.clone() };
            out += &format!(
                "theorem p{p}_v{i} : ∀ n σ', Steps n p{p} s{p} .skip σ' → σ' {i} = {lv} :=\n  vector_sound _ _ _ _ (by decide) (by decide)\ntheorem p{p}_b{i} : (evalB p{p} s{p}).map (fun σ => σ {i}) = some {lv} := by decide\n"
            );
        }
        p += 1;
    }

    out += "\nend RCE.ParVectors\n";
    out
}

#[test]
fn lean_vectors_match_evaluator() {
    let text = generate();
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../lean/RCE/ParVectors.lean");
    if std::env::var("RCE_BLESS").is_ok_and(|v| v == "1") {
        std::fs::write(&path, &text).unwrap();
    }
    let have = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(have == text, "ParVectors.lean is stale; rerun with RCE_BLESS=1 and lake build");
}
